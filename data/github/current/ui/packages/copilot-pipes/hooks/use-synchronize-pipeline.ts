import {useEffect, useMemo} from 'react'
import {usePipesService} from '../contexts/PipesServiceProvider'
import {useGetPipesState, usePipesDispatch, usePipesStateLens} from '../contexts/PipesStateProvider'
import {dummyPipelines, isDummyPipeline} from '../test-utils/dummy-pipelines'
import type {CopilotChatState} from '@github-ui/copilot-chat/utils/copilot-chat-reducer'
import type {CopilotChatMessage} from '@github-ui/copilot-chat/utils/copilot-chat-types'
import {getLatestPipe} from '../utils/chat-helpers'
import {currentPipeline, useHasValidationErrors} from '../state/lenses'

const isDev = process.env.NODE_ENV === 'development'

/**
 * This hook handles all synchronization between:
 * - Our application state
 * - Our pipeline/execution state storage
 * - The chat history
 */
export function useSynchronizePipeline(chatState: CopilotChatState) {
  useInitializeDevPipelines()
  useSyncPipelineFromChat(chatState)
  useStorePipeline(chatState.selectedThreadID)
  useStoreExecutionState()
}

function useInitializeDevPipelines() {
  const dispatch = usePipesDispatch()

  useEffect(() => {
    if (!isDev) return
    dispatch({type: 'INITIALIZE_PIPELINES', pipelines: dummyPipelines})
  }, [isDev, dispatch])
}

/**
 * Whenever the latest pipeline in the chat changes, evaluate which
 * version of the pipeline should be put in the application state.
 */
function useSyncPipelineFromChat(chatState: CopilotChatState) {
  const dispatch = usePipesDispatch()
  const pipesService = usePipesService()
  const pipelineFromChat = useLatestPipelineFromChat(chatState.selectedThreadID, chatState.messages)
  const getPipesState = useGetPipesState()

  useEffect(() => {
    let cancelled = false

    const restoreSavedPipeline = async () => {
      if (!chatState.selectedThreadID) return

      const savedPipeline = await pipesService.getPipeline(chatState.selectedThreadID)

      // TODO: eventually, we should add version numbers and use whichever is more recent.
      // For now we have do some tricky checks: if we are initializing (i.e. we are loading
      // a thread or starting a thread) then we should prefer a saved pipeline if it exists.
      // Otherwise (we're getting a fresh version of the pipeline back from a new chat
      // message) we should prefer the chat version to a stored version.
      const pipesState = getPipesState()
      const pipelineInState = currentPipeline(pipesState)
      const initializing = !pipelineInState || isDummyPipeline(pipelineInState)
      // The formatter likes to put this all one one line with no parentheses, which is madness
      // prettier-ignore
      const pipelineToUse = initializing
        ? (savedPipeline ?? pipelineFromChat)
        : (pipelineFromChat ?? savedPipeline)

      if (cancelled) return
      if (!pipelineToUse) return

      dispatch({type: 'ADD_PIPELINE', pipeline: pipelineToUse})

      const executionState = await pipesService.getExecutionState(pipelineToUse.id)
      if (cancelled) return
      if (!executionState) return

      dispatch({type: 'RESTORE_EXECUTION_STATE', executionState})
    }

    restoreSavedPipeline()
    return () => {
      cancelled = true
    }
  }, [pipelineFromChat, dispatch, pipesService])
}

/**
 * For the purpose of only storing *new* pipelines, we want to have each
 * pipeline generated by the chat always be the same object. However, getLatestPipe
 * sanitizes the pipeline, which creates a new object. We know that the
 * chat messages do not change after they are sent, so a pipeline created
 * as part of a given message is always the same. This means we can safely
 * memoize on the message ID and ignore the linter.
 */
function useLatestPipelineFromChat(selectedThreadId: string | null, messages: CopilotChatMessage[]) {
  const {pipeline, messageId} = getLatestPipe(selectedThreadId, messages) ?? {}
  // eslint-disable-next-line react-compiler/react-compiler
  // eslint-disable-next-line react-hooks/exhaustive-deps
  return useMemo(() => pipeline, [messageId])
}

/**
 * Whenever the pipeline updates, save it unless it is invalid
 */
function useStorePipeline(threadID: string | null) {
  const pipesService = usePipesService()
  const pipeline = usePipesStateLens(currentPipeline)
  const hasValidationErrors = useHasValidationErrors()

  useEffect(() => {
    if (!pipeline || !threadID) return
    if (hasValidationErrors) return
    if (isDummyPipeline(pipeline)) return
    pipesService.updatePipeline(threadID, pipeline)
  }, [pipeline, pipesService, hasValidationErrors, threadID])
}

/**
 * Whenever the execution state updates, save it
 */
function useStoreExecutionState() {
  const pipesService = usePipesService()
  const execution = usePipesStateLens(s => s.executionState)
  const pipelineID = usePipesStateLens(s => currentPipeline(s)?.id)

  useEffect(() => {
    if (!pipelineID) return
    pipesService.updateExecutionState(pipelineID, execution.iteration, execution)
  }, [pipelineID, execution, pipesService])
}
