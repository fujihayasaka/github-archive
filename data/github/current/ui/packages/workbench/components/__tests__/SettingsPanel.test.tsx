import {mockClientEnv} from '@github-ui/client-env/mock'
import {screen} from '@testing-library/react'

import {renderWorkbenchStore, type WorkbenchStoreProps} from '../../__tests__/WorkbenchStoreWrapper'
import {useIterationHistory} from '../../contexts/IterationHistoryContext'
import {useWorkbenchContext} from '../../contexts/WorkbenchContext'
import {SettingsPanel} from '../SettingsPanel'

jest.mock('../../contexts/IterationHistoryContext', () => ({
  useIterationHistory: jest.fn(),
}))

jest.mock('../../contexts/WorkbenchContext', () => ({
  useWorkbenchContext: jest.fn(),
}))

jest.mock('../../hooks/use-workbench', () => ({
  useWorkbench: jest.fn(() => ({
    name: 'Test Workbench',
    description: 'Test Description',
  })),
}))

jest.mock('../../hooks/use-check-name', () => ({
  useCheckName: jest.fn().mockReturnValue([{status: 'none'}, jest.fn()]),
  isError: jest.fn().mockReturnValue(false),
}))

const renderSettingsPanel = (storeProps: WorkbenchStoreProps = {}) => {
  return renderWorkbenchStore({
    children: <SettingsPanel repositoryUrl={undefined} onCreateRepository={jest.fn()} />,
    ...storeProps,
  })
}

const mockUseIterationHistory = useIterationHistory as jest.Mock
const mockUseWorkbenchContext = useWorkbenchContext as jest.Mock

describe('SettingsPanel', () => {
  beforeEach(() => {
    jest.clearAllMocks()

    mockUseIterationHistory.mockReturnValue({
      previousRefinements: [
        {
          id: '1',
          prompt: 'Test prompt',
          files: {},
        },
      ],
    })
  })

  mockUseWorkbenchContext.mockReturnValue({
    isFetching: false,
    initialPromptSubmitted: {
      current: true,
    },
  })

  it('should render with default props', () => {
    renderSettingsPanel()

    expect(screen.getByText('Generated by Spark')).toBeInTheDocument()
    expect(screen.getByText('Delete spark')).toBeInTheDocument()

    expect(screen.getByRole('textbox', {name: 'Name *'})).toBeInTheDocument()
    expect(screen.getByRole('textbox', {name: 'Description'})).toBeInTheDocument()

    expect(screen.getByRole('button', {name: 'Save changes'})).toBeInTheDocument()
    expect(screen.getByRole('button', {name: 'Delete'})).toBeInTheDocument()
  })

  it('should render with inputs enabled if globalReadOnly without FF', () => {
    renderSettingsPanel({readOnly: true})

    expect(screen.getByRole('textbox', {name: 'Name *'})).not.toBeDisabled()
    expect(screen.getByRole('textbox', {name: 'Description'})).not.toBeDisabled()
    expect(screen.getByRole('button', {name: 'Delete'})).not.toBeDisabled()
    expect(screen.getByRole('button', {name: 'Save changes'})).not.toBeDisabled()
  })

  it('should render with inputs disabled if globalReadOnly with FF', () => {
    mockClientEnv({
      featureFlags: ['workbench_store_readonly'],
    })
    renderSettingsPanel({readOnly: true})

    expect(screen.getByRole('textbox', {name: 'Name *'})).toBeDisabled()
    expect(screen.getByRole('textbox', {name: 'Description'})).toBeDisabled()
    expect(screen.getByRole('button', {name: 'Delete'})).not.toBeDisabled()
    expect(screen.getByRole('button', {name: 'Save changes'})).toBeDisabled()
  })

  it('should render with inputs disabled if codespace is starting', () => {
    mockClientEnv({
      featureFlags: ['workbench_store_readonly'],
    })
    renderSettingsPanel({readOnly: true, status: {codespace: 'starting'}})

    expect(screen.getByRole('textbox', {name: 'Name *'})).toBeDisabled()
    expect(screen.getByRole('textbox', {name: 'Description'})).toBeDisabled()
    expect(screen.getByRole('button', {name: 'Delete'})).not.toBeDisabled()
    expect(screen.getByRole('button', {name: 'Save changes'})).toBeDisabled()
  })
})
