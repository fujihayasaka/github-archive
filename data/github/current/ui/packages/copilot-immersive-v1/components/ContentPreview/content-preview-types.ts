import {referenceID} from '@github-ui/copilot-chat/utils/copilot-chat-helpers'
import {
  type CopilotChatReference,
  type DraftIssueReference,
  type FileReference,
  type IssueReference,
  NullMessageId,
  type ThreadScopedFileReference,
} from '@github-ui/copilot-chat/utils/copilot-chat-types'

export interface ContentPreviewContext {
  /** All items by ID, regardless of visibility. */
  items: ItemsMap
  /**
   * Given a base ID, get all the versions associated with it. For unversioned items this will be a single-element
   * array. Versions are sorted by timestamp.
   */
  versionedItems: VersionedItemsMap
  /** Visible item IDs, in order. If empty, the pane is closed. */
  openItems: readonly PreviewableContentIdentifier[]
  /** Item IDs that were visible before switching subthreads. Used to restore open files after new subthread loads */
  openItemsBeforeSubthreadChange: readonly PreviewableContentIdentifier[]
  /** Currently selected item. */
  selectedItem: PreviewableContentIdentifier | undefined
  /** Whether the preview pane is open. */
  previewPaneOpen: boolean
  /** Whether the loading UI is visible */
  showLoadingState: boolean

  /** Add or update an item. */
  updateItem: (item: PreviewableContent) => void
  /** Set the items to restore after a subthread change. */
  setOpenItemsBeforeSubthreadChange: (items: readonly PreviewableContentIdentifier[]) => void
  /** Open the item, selecting it if specified. Does **not** open the pane if the pane is closed. */
  openItem: (id: PreviewableContentIdentifier, selectItem?: boolean) => void
  /** Close (hide) the item. */
  closeItem: (id: PreviewableContentIdentifier) => void
  /** Close all items. */
  closeAllItems: () => void
  /** Close the entire preview pane. Preserves open items for when reopened. */
  closePreviewPane: () => void
  /** Open the preview pane and restore any previously open items. */
  openPreviewPane: () => void
  /** Removes the items and openItems with the given IDs, or all if undefined  */
  removeItems: (ids?: PreviewableContentIdentifier[]) => void
  /** Shows the loading UI */
  enableLoadingState: () => void
  /** Hides the loading UI */
  disableLoadingState: () => void
}

export type PreviewableContentTypes = 'file' | 'issue' | 'new-issue' | 'image' | 'file-reference'

export type PreviewableContentIdentifier = `${PreviewableContentTypes}:${string}`

export type VersionedPreviewableContentIdentifier = `${PreviewableContentIdentifier}#${string}`

export interface PreviewableContentBase {
  messageId: string
  name: string
  id: PreviewableContentIdentifier
  type: PreviewableContentTypes
}

interface VersionedPreviewableContentBase extends PreviewableContentBase {
  id: VersionedPreviewableContentIdentifier
  /** Indicates whether the user has edited this unsaved/draft content */
  isUserEdited: boolean
}

export interface File extends VersionedPreviewableContentBase {
  id: `file:${string}#${number}.${number}` | `file:${string}#${number}`
  language: string
  value: string
  type: 'file'
  name: string
  isStreaming: boolean
  timestamp: Date
  /** if this file is from a reference (i.e. not generated by Copilot) this will be set */
  reference?: FileReference | ThreadScopedFileReference
}

export interface Issue extends PreviewableContentBase {
  number: number
  owner: string
  repo: string
  href: string
  type: 'issue'
  id: `issue:${string}`
}

export interface DraftIssue extends VersionedPreviewableContentBase {
  /** The issue number/ID is not known until the issue is created, so we ask Copilot to create an identifier for us called a tag */
  tag: string
  parentTag?: string
  repository?: string
  type: 'new-issue'
  id: `${DraftIssue['type']}:${string}#${number}`
  template?: string
  body?: string
  assignees: string[]
  labels: string[]
  issueType?: string
  projects: string[]
  milestone?: string
  isStreaming?: boolean
}

export interface Image extends PreviewableContentBase {
  altText: string
  type: 'image'
  url: string
  id: `image:${string}`
}

export type VersionedPreviewableContent = File | DraftIssue
export type PreviewableContent = Issue | Image | VersionedPreviewableContent

/**
 * A map of unversioned identifiers to a list of versioned identifiers.
 */
export type VersionedItemsMap = ReadonlyMap<PreviewableContentIdentifier, PreviewableContentIdentifier[]>

/**
 * A map of identifiers to the content they identify.
 */
export type ItemsMap = ReadonlyMap<PreviewableContentIdentifier, PreviewableContent>

export function stripVersionFromId<T extends PreviewableContentIdentifier>(id: T): T {
  return id.split('#')[0] as T
}

export function getRevisionNumber(id: PreviewableContentIdentifier, versionedItems: VersionedItemsMap): number | null {
  const baseId = stripVersionFromId(id)
  const versions = versionedItems.get(baseId) ?? []
  const versionIndex = versions.indexOf(id)
  return versions.length > 1 && versionIndex !== -1 ? versionIndex + 1 : null
}

export function makeReferenceFromFile(item: File): ThreadScopedFileReference {
  return {
    type: 'thread-scoped-file',
    name: item.name,
    language: item.language,
    text: item.value,
  }
}

export function getItemIdFromThreadScopedFileReference(
  ref: ThreadScopedFileReference,
  messageIndex: number,
): File['id'] {
  return `file:${ref.name}#${messageIndex}` // TODO: this should be messageId once we have a stable value for that
}

export function getItemVersionForReference(
  ref: CopilotChatReference,
  messageIndex: number,
  versionedItems: VersionedItemsMap,
): number | undefined {
  switch (ref.type) {
    case 'thread-scoped-file':
      return getRevisionNumber(getItemIdFromThreadScopedFileReference(ref, messageIndex), versionedItems) ?? undefined
    case 'draft-issue':
      return getRevisionNumber(makeVersionedItemFromReference({ref, messageIndex}).id, versionedItems) ?? undefined
  }
}

export function makeItemFromThreadScopedFileReference(
  ref: ThreadScopedFileReference,
  messageIndex: number,
  messageId = NullMessageId,
  timestamp?: string,
): File {
  return {
    type: 'file',
    id: getItemIdFromThreadScopedFileReference(ref, messageIndex),
    reference: ref,
    messageId,
    name: ref.name,
    language: ref.language,
    value: ref.text,
    timestamp: timestamp ? new Date(timestamp) : new Date(),
    isStreaming: false,
    // If no message ID is provided, it's because the file has been edited and the message does not yet exist
    isUserEdited: messageId === NullMessageId,
  }
}

export function makeItemFromFileReference(ref: FileReference, messageId?: string, timestamp?: string): File {
  return {
    type: 'file',
    id: `file:${referenceID(ref)}#0`,
    reference: ref,
    messageId: messageId ?? NullMessageId,
    name: ref.path,
    language: ref.languageName ?? '',
    value: '',
    isStreaming: true,
    isUserEdited: false,
    timestamp: timestamp ? new Date(timestamp) : new Date(),
  }
}

export function makeItemFromIssueReference(ref: IssueReference, messageId?: string): Issue {
  return {
    type: 'issue',
    id: `issue:${ref.number}`,
    messageId: messageId ?? NullMessageId,
    name: ref.title ?? '',
    number: ref.number,
    owner: ref.repository.owner,
    repo: ref.repository.name,
    href: ref.url,
  }
}

function makeReferenceFromNewIssue(item: DraftIssue): DraftIssueReference {
  return {
    type: 'draft-issue',
    tag: item.tag,
    parentTag: item.parentTag,
    title: item.name,
    description: item.body,
    repository: item.repository,
    template: item.template,
    assignees: item.assignees,
    labels: item.labels,
    issueType: item.issueType,
    projects: item.projects,
    milestone: item.milestone,
  }
}

function makeItemFromDraftIssueReference({
  ref,
  messageId = NullMessageId,
  messageIndex,
}: {
  ref: DraftIssueReference
  messageIndex: number
  messageId?: string
}): DraftIssue {
  return {
    type: 'new-issue',
    id: `new-issue:${ref.tag}#${messageIndex}`,
    tag: ref.tag,
    parentTag: ref.parentTag,
    repository: ref.repository,
    name: ref.title,
    body: ref.description,
    assignees: ref.assignees ?? [],
    labels: ref.labels ?? [],
    issueType: ref.issueType,
    projects: ref.projects ?? [],
    milestone: ref.milestone,
    isUserEdited: messageId === NullMessageId, // If no message ID is provided, it's because the file has been edited and the message does not yet exist
    messageId,
    isStreaming: false,
    template: ref.template,
  }
}

export function makeReferenceFromVersionedItem(item: File): ThreadScopedFileReference
export function makeReferenceFromVersionedItem(item: DraftIssue): DraftIssueReference
export function makeReferenceFromVersionedItem(item: PreviewableContent): CopilotChatReference | null
export function makeReferenceFromVersionedItem(item: PreviewableContent): CopilotChatReference | null {
  switch (item.type) {
    case 'file':
      return makeReferenceFromFile(item)
    case 'new-issue':
      return makeReferenceFromNewIssue(item)
    default:
      return null
  }
}

export function makeVersionedItemFromReference({
  ref,
  messageIndex,
  messageId,
  timestamp,
}: {
  ref: ThreadScopedFileReference
  messageIndex: number
  messageId?: string
  timestamp?: string
}): File
export function makeVersionedItemFromReference({
  ref,
  messageIndex,
  messageId,
}: {
  ref: DraftIssueReference
  messageIndex: number
  messageId?: string
}): DraftIssue
export function makeVersionedItemFromReference({
  ref,
  messageIndex,
}: {
  ref: CopilotChatReference
  messageIndex: number
  messageId?: string
  timestamp?: string
}): VersionedPreviewableContent | null
export function makeVersionedItemFromReference({
  ref,
  messageIndex,
  messageId,
  timestamp,
}: {
  ref: CopilotChatReference
  messageIndex: number
  messageId?: string
  timestamp?: string
}): VersionedPreviewableContent | null {
  switch (ref.type) {
    case 'thread-scoped-file':
      return makeItemFromThreadScopedFileReference(ref, messageIndex, messageId, timestamp)
    case 'draft-issue':
      return makeItemFromDraftIssueReference({ref, messageIndex, messageId})
    default:
      return null
  }
}
