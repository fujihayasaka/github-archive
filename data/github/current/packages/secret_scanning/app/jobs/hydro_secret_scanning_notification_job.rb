# typed: true
# frozen_string_literal: true

# HydroSecretScanningNotificationJob processes TokenScanNotify hydro messages
# and sends summary emails to repository admins and commit authors when secrets are found.
# Message schema: github.v1.TokenScanNotify
#
# This job handles both:
# - Admin notifications (all scopes) to repository admins and subscribed users
# - Author notifications (commit-scoped only) to commit/content authors
class HydroSecretScanningNotificationJob < HydroMessageJob
  include SecretScanning::Features::FeatureFlagHelper
  include GitHub::Memoizer

  # This job can be queued via either admin or author notification queues
  queue_as :hydro_secret_scanning_admin_notification

  retry_on_dirty_exit
  retry_on *T.unsafe(Resiliency::Response::UnavailableExceptions)
  retry_on Freno::Throttler::Error, Freno::Error, Freno::Throttler::WaitedTooLong

  FAILBOT_APP_NAME = "token-scanning-service"

  sig { void }
  def perform
    repo_id = message[:repository_id]
    scope = message[:scope]

    # Emit received metric first, before any processing that might fail
    GitHub.dogstats.increment(
      "secret_scanning.notification_job.received",
      tags: ["scope:#{scope}", "queue:#{queue}"]
    )

    GitHub.logger.with_named_tags(
      "code.namespace": self.class.name,
      "gh.repo.id": repo_id,
      "gh.queue": queue,
      "gh.scope": scope
    ) do
      process_notifications
    end
  rescue => e
    Failbot.report(e, { app: FAILBOT_APP_NAME })
    GitHub.logger.error(
      "Error processing TokenScanNotify message",
      "code.namespace": self.class.name,
      "exception.message": e.message,
      "gh.repo.id": message[:repository_id]
    )
    raise e
  end

  private

  sig { returns(::SecretScanning::NotificationService) }
  memoize def notification_service
    ::SecretScanning::NotificationService.new(caller_namespace: T.must(self.class.name))
  end

  sig { void }
  def process_notifications
    repo_id = message[:repository_id]
    repo = T.let(nil, T.nilable(Repository))
    business = T.let(nil, T.nilable(Business))

    if FeatureFlag.vexi.enabled?(:secret_scanning_use_notification_service, default: false)
      repo = with_read { notification_service.get_repo(repo_id) }
      return if repo.nil?

      business = notification_service.get_business(repo)
    else
      with_read do
        repo = if FeatureFlag.vexi.enabled?(:repos_by_id_lib, default: false)
          T.cast(Repositories.domain.by_id(repo_id), T.nilable(Repository)) # rubocop:todo GitHub/AvoidCast
        else
          Repository.find_by(id: repo_id)
        end
      end

      if repo.nil?
        GitHub.logger.info(
          "Repository not found, skipping message",
          "code.namespace": self.class.name,
          "gh.repo.id": repo_id
        )

        return
      end

      # Does not have to be multitenant enterprise for it to be a EMU repo
      if GitHub.multi_tenant_enterprise?
        business = GitHub::CurrentTenant.unscope { repo.owner&.business }
      else
        business = repo.owner&.business
      end
    end

    GitHub::CurrentTenant.set(business) do
      unless ::SecretScanning::Features::Repo::TokenScanning.new(repo).enabled?
        GitHub.logger.info(
          "Secret scanning not enabled on repo, skipping message",
          "code.namespace": self.class.name,
          "gh.repo.id": repo_id
        )

        return
      end

      users_to_notify = T.let(repo.token_scanning_users_to_notify, T::Array[User])

      if users_to_notify.empty?
        GitHub.logger.info(
          "No subscribed users to notify",
          "code.namespace": self.class.name,
          "gh.repo.id": repo_id
        )
      end

      # message is actually a protobuf message decoded into a hash with values of varying types rather than an
      # actual Hydro::Schemas::Github::V1::TokenScanNotify class generated by sorbet, but we can use these generated
      # classes to let us know what's in each hash

      # results: T::Array[Hydro::Schemas::Github::V1::TokenScanNotify::TokenGroup]
      results = T.let(message[:token_groups], T::Array[T::Hash[Symbol, T.untyped]])
      # scope: String
      scope = T.let(message[:scope], String)
      # open_alert_count: Integer
      open_alert_count = message[:open_alert_count]
      # scan_count: Integer
      scan_count = T.let(message[:total_scan_alert_count], Integer)
      # scan_source: Symbol
      scan_source = message[:scan_source]

      if FeatureFlag.vexi.enabled?(:secret_scanning_use_notification_service, default: false)
        # Filter users for backfill scans - returns nil if notification should be skipped
        filtered_users = notification_service.filter_users_for_backfill(users_to_notify, repo, scope, scan_source)
        return if filtered_users.nil?

        users_to_notify = filtered_users
      else
        # Config change operations can result in tokens getting removed from the UI so we need slightly different behavior.

        is_repo_scope = scope == "repo" || scope == "generic_secrets_repo"
        is_org_or_enterprise_backfill_scan = is_repo_scope && (scan_source == :SCAN_SOURCE_ORGANIZATION || scan_source == :SCAN_SOURCE_BUSINESS)

        # If we're sending the new joint email, we want to email repo admins only, not org/enterprise admins and security managers.
        # Therefore, remove them.

        # See `HydroSecretScanningJobGroupEventProcessorJob` for how we notify org/enterprise admins and security managers per
        # org/enterprise enablement.
        owner = repo.owner
        if is_org_or_enterprise_backfill_scan
          owner_admins = T.let([], T::Array[User])
          if !owner.organization?
            # Noop and skip the rest of this logic.
            return
          elsif owner.business != nil
            owner_admins = ::SecretScanning::Features::Business::TokenScanning.new(owner.business).get_admins_to_notify
          elsif owner.is_a?(Organization)
            owner_admins = ::SecretScanning::Features::Org::TokenScanning.new(owner).get_admins_to_notify
          end
          users_to_notify = users_to_notify - owner_admins
        end
      end

      # Send admin notifications
      send_admin_notifications(repo, repo_id, results, users_to_notify, scope, open_alert_count, scan_count)

      # Send author notifications (only for commit-scoped events)
      if FeatureFlag.vexi.enabled?(:secret_scanning_use_hydro_for_author_notifications, default: false)
        notify_secret_authors(repo, repo_id, results, users_to_notify, scope, scan_count, business)
      else
        GitHub.logger.info(
          "Skipping author notifications for TokenScanNotify message: feature flag disabled",
          "code.namespace": self.class.name,
          "gh.repo.id": repo_id,
          "gh.scope": scope
        )
      end
    end
  end

  sig do
    params(
      repo: Repository,
      repo_id: Integer,
      results: T::Array[T::Hash[Symbol, T.untyped]],
      users_to_notify: T::Array[User],
      scope: String,
      open_alert_count: T.nilable(Integer),
      scan_count: Integer
    ).void
  end
  def send_admin_notifications(repo, repo_id, results, users_to_notify, scope, open_alert_count, scan_count)
    unless users_to_notify.empty? || results.empty?
      tags = ["scope:#{scope}"]

      if FeatureFlag.vexi.enabled?(:secret_scanning_use_notification_service, default: false)
        mail = SecretScanningMailer.admin_token_scanning_summary(repo, results, users_to_notify, scope, open_alert_count, scan_count)
        notification_service.deliver_and_record(mail, metric_name: "admin_token_scanning_summary", tags: tags)
      else
        SecretScanningMailer.admin_token_scanning_summary(repo, results, users_to_notify, scope, open_alert_count, scan_count).deliver_later
        GitHub.dogstats.increment("secret_scanning.notification_job.admin_email_sent", tags: tags)
      end

      GitHub.logger.info(
        "Admin summary email queued for delivery",
        "code.namespace": self.class.name,
        "gh.repo.id": repo_id
      )

      # Track end-to-end latency from message timestamp
      if timestamp.present?
        duration_ms = (Time.now - Time.at(timestamp)).to_f * 1000
        GitHub.dogstats.distribution(
          "secret_scanning.notification_job.admin_email.duration",
          duration_ms,
          tags: tags
        )
      end
    end
  end

  sig do
    params(
      repo: Repository,
      repo_id: Integer,
      results: T::Array[T::Hash[Symbol, T.untyped]],
      subscribed_users: T::Array[User],
      scope: String,
      scan_count: Integer,
      business: T.nilable(Business)
    ).void
  end
  def notify_secret_authors(repo, repo_id, results, subscribed_users, scope, scan_count, business)
    return unless [SecretScanningMailer::TOKEN_SCANNING_SCOPE[:commit_scoped],
          SecretScanningMailer::TOKEN_SCANNING_SCOPE[:bypassed_as_false_positive_scoped],
          SecretScanningMailer::TOKEN_SCANNING_SCOPE[:bypassed_as_used_in_tests_scoped],
          SecretScanningMailer::TOKEN_SCANNING_SCOPE[:bypassed_as_fix_later_scoped],
          SecretScanningMailer::TOKEN_SCANNING_SCOPE[:generic_secrets_commit_scoped]].include?(scope)

    token_results_by_author_email = T.let(Hash.new { |h, key| h[key] = [] }, T::Hash[String, T::Array[T::Hash[Symbol, T.untyped]]])
    with_read do
      results.each do |result|
        result[:tokens].each do |token|
          content_type = token[:first_location][:content_type]
          if content_type == :REPOSITORY_BLOB
            commit = fetch_commit(repo, token)
            commit&.author_emails&.each do |email|
              user = User.find_by_email(email, business: business)
              add_author_email(token_results_by_author_email, repo, user, email, result, subscribed_users)
            end
            next
          end
          if content_type == :WIKI_BLOB
            commit = fetch_wiki_commit(repo, token)
            commit&.author_emails&.each do |email|
              user = User.find_by_email(email, business: business)
              add_author_email(token_results_by_author_email, repo, user, email, result, subscribed_users)
            end
            next
          end

          content_number = token[:first_location][:content_number]
          content_id = token[:first_location][:content_id]
          user = case content_type
          when :ISSUE_TITLE, :ISSUE_BODY, :PULL_REQUEST_TITLE, :PULL_REQUEST_BODY
            repo.issues.find_by(number: content_number)&.user # domain-isolation-query-violation:ignore:packages/issues (SELECT)
          when :ISSUE_COMMENT, :PULL_REQUEST_COMMENT
            IssueComments::Public.by_id(content_id, repository_id: repo.id)&.user
          when :PULL_REQUEST_REVIEW, :PULL_REQUEST_TIMELINE_COMMENT
            pr = repo.issues.find_by(number: content_number)
            T.must(pr.pull_request).reviews.find_by(id: content_id)&.user if pr
          when :PULL_REQUEST_REVIEW_COMMENT
            pr = repo.issues.find_by(number: content_number)
            repo.pull_request_review_comments.find_by(id: content_id)&.user if pr
          when :DISCUSSION_TITLE, :DISCUSSION_BODY
            repo.discussions.find_by(number: content_number)&.user
          when :DISCUSSION_COMMENT
            repo.discussion_comments.find_by(id: content_id)&.user
          end
          email = user&.emails&.verified&.first&.email
          add_author_email(token_results_by_author_email, repo, user, email, result, subscribed_users)
        end
      end
    end

    if token_results_by_author_email.empty?
      GitHub.logger.info(
        "No commit authors to notify",
        "code.namespace": self.class.name,
        "gh.repo.id": repo_id
      )
      return
    end

    tags = ["scope:#{scope}"]

    if FeatureFlag.vexi.enabled?(:secret_scanning_use_notification_service, default: false)
      token_results_by_author_email.each do |email, author_results|
        mail = SecretScanningMailer.secret_author_token_scanning_summary(repo, author_results, email, scope, scan_count, business)
        notification_service.deliver_and_record(mail, metric_name: "secret_author_token_scanning_summary", tags: tags)
      end
    else
      token_results_by_author_email.each do |email, author_results|
        SecretScanningMailer.secret_author_token_scanning_summary(repo, author_results, email, scope, scan_count, business).deliver_later
      end
      GitHub.dogstats.increment("secret_scanning.notification_job.author_email_sent", tags: tags)
    end

    if timestamp.present?
      duration_ms = (Time.now - Time.at(timestamp)).to_f * 1000
      GitHub.dogstats.distribution(
        "secret_scanning.notification_job.author_email.duration",
        duration_ms,
        tags: tags
      )
    end

    GitHub.logger.info(
      "Commit author summary emails queued for delivery",
      "code.namespace": self.class.name,
      "gh.repo.id": repo_id
    )
  end

  sig do
    params(
      repo: Repository,
      token: T::Hash[Symbol, T.untyped] # token: Hydro::Schemas::Github::V1::TokenScanNotify::TokenGroup::Token
    ).returns(T.nilable(Commit))
  end
  def fetch_commit(repo, token)
    commit_oid = token[:first_location][:commit_oid]

    begin
      repo.commits.find(commit_oid)
    rescue GitRPC::InvalidObject,
           GitRPC::ObjectMissing,
           GitRPC::NetworkError,
           ArgumentError => e

      log_commit_fetch_error(e, repo, commit_oid, token, "fetch_commit", "Error retrieving commit for repo")
      nil
    end
  end

  sig do
    params(
      repo: Repository,
      token: T::Hash[Symbol, T.untyped] # token: Hydro::Schemas::Github::V1::TokenScanNotify::TokenGroup::Token
    ).returns(T.nilable(Commit))
  end
  def fetch_wiki_commit(repo, token)
    commit_oid = token[:first_location][:commit_oid]

    begin
      repo.find_wiki_commit(commit_oid)
    rescue GitRPC::InvalidObject,
           GitRPC::ObjectMissing,
           GitRPC::NetworkError,
           ArgumentError => e

      log_commit_fetch_error(e, repo, commit_oid, token, "fetch_wiki_commit", "Error retrieving commit for wiki")
      nil
    end
  end

  sig do
    params(
      token_results_by_author_email: T::Hash[String, T::Array[T::Hash[Symbol, T.untyped]]],
      repo: Repository,
      user: T.nilable(User),
      email: T.nilable(String),
      result: T::Hash[Symbol, T.untyped], # result: Hydro::Schemas::Github::V1::TokenScanNotify::TokenGroup
      subscribed_users: T::Array[User]
    ).void
  end
  def add_author_email(token_results_by_author_email, repo, user, email, result, subscribed_users)
    return if email.nil? || user.nil?

    return if do_not_notify_author?(repo, user, email, subscribed_users)

    # token_results_by_author_email creates a default empty array for each key, so token_results_by_author_email[email] will never be nil
    token_results = T.must(token_results_by_author_email[email])

    # If a result has already been added, do not add it again.
    return if token_results.include?(result)

    token_results.push(result)
  end

  # 1) If the secret author is a subscribed user for the repo, do not notify.
  #    Subscribed users are repo admins, or are subscribed to security alerts via settings,
  #    and already receive notification emails for all secrets found in the repo.
  #
  # 2) Do not notify if the secret author's email is not verified.
  # 3) Do not notify if the secret author no longer has access to the repo.
  sig { params(repo: Repository, user: T.nilable(User), email: T.nilable(String), subscribed_users: T::Array[User]).returns(T::Boolean) }
  def do_not_notify_author?(repo, user, email, subscribed_users)
    return true unless user.present?
    # commit author was already added in token_scanning_users_to_notify
    return true if subscribed_users.include?(user)

    if user.is_enterprise_managed?
      email = user.add_emu_shortcode_to_emails(user.email)
    end

    # We only send emails to verified emails
    return true unless user.emails.where(email: email).first&.verified?

    # ensure user has access to the repo
    return true unless ::SecretScanning::AccessControl::CommitAuthorView.new(repo).has_access_to_repository?(user)

    # Always notify commit authors (unless they're already getting the admin email)
    false
  end

  sig do
    params(
      exception: StandardError,
      repo: Repository,
      commit_oid: String,
      token: T::Hash[Symbol, T.untyped],
      function_name: String,
      error_message: String
    ).void
  end
  def log_commit_fetch_error(exception, repo, commit_oid, token, function_name, error_message)
    GitHub.logger.error(
      error_message,
      "code.namespace": self.class.name,
      "code.function": function_name,
      "gh.repo.id": repo.id,
      "commit_oid": commit_oid,
      "token_scan_result_number": token[:number],
      "exception.message": exception.message,
      "exception.type": exception.class.name
    )
  end
end
