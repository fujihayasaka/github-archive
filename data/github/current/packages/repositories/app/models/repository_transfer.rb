# typed: false
# frozen_string_literal: true

# Public: A pending action changing the ownership of a repository.
class RepositoryTransfer < ApplicationRecord::Domain::Repositories
  include Repository::EnterpriseManagedUserMethods

  # Internal: The signed auth token name used for transfer requests.
  SCOPE = "RepositoryTransfer:request"

  # Internal: A Map of Symbols to Fixnums.
  enum :state, { requested: 0, responded: 1 }

  DISABLED_REASON = {
    cant_delete_repos_on_this_appliance: "Users cannot transfer repositories on this appliance",
    members_cant_delete_repositories: "Organization members cannot transfer repositories",
    prevented_by_ruleset: "Ruleset(s) are preventing this repository from being transferred.",
  }.freeze

  CANNOT_TRANSFER_FROM_EMU_REASON = "You cannot transfer a repository to a user or organization outside of your enterprise managed business"
  CANNOT_TRANSFER_TO_EMU_REASON = "Cannot find new owner" # to not reveal the existence of the EMU user/org

  before_validation :set_initial_new_name, on: :create

  validates_presence_of  :repository_id
  validates_presence_of  :requester_id
  validates_uniqueness_of :repository_id

  validates :state, presence: true
  validates :new_name, length: { maximum: Repository::NAME_MAX_LENGTH }

  validate :repository_can_be_transferred
  validate :internal_repository_must_stay_in_enterprise
  validate :requester_can_admin_repository
  validate :requester_is_not_blocked_by_target
  validate :target_owner_exists
  validate :original_and_target_owners_are_different
  validate :target_repo_does_not_exist
  validate :target_has_no_conflicting_fork
  validate :target_can_accept_repository
  validate :target_has_sufficient_seats
  validate :target_can_accept_outside_collaborators
  validate :repo_owner_is_not_spammy
  validate :repo_not_locked_on_migration
  validate :permission_on_new_org_repo
  validate :target_owner_is_not_blocked_personal_namespace
  validate :from_org_to_self
  validate :org_repo_deletion_restriction
  validate :valid_emu_context, if: :dotcom?
  validate :ensure_not_retired_namespace
  validate :valid_custom_properties
  validate :new_owner_under_repository_limit

  with_options if: :responded? do |responded|
    responded.validates_presence_of  :responder_id
    responded.validate :responder_can_admin_target
  end

  # Public: The repo being transferred.
  include ::Repositories::BelongsToRepository
  belongs_to_repository_via_domain
  destroy_in_background_with :repository

  # Public: The User who started this transfer.
  belongs_to :requester, class_name: "User"

  # Public: The User who finished this transfer.
  belongs_to :responder, class_name: "User"

  # Public: The User or Organization who ends up with the repo.
  belongs_to :target, class_name: "User"

  attr_accessor :requested_target
  attr_accessor :custom_properties

  # Public: Remove any RepositoryTransfers aimed at target. Returns nothing.
  def self.clear_target(target)
    where(target_id: target).delete_all
  end

  # Public: Find a RepositoryTransfer matching this request token String.
  #
  # token_str - A signed auth token String generated by self.start()
  #
  # Returns the matching RepositoryTransfer.
  # Returns :expired_token if the token is expired.
  # Returns nil for otherwise invalid tokens.
  # Returns nil if the repository's owner has changed since token generation.
  def self.from(token_str)
    token = User.verify_signed_auth_token(
      token: token_str,
      scope: SCOPE,
    )

    if !token.valid?
      return :expired_token if token.expired?
      return nil
    end

    GitHub.dogstats.increment "repository_transfer", tags: ["token_version:#{token.version}"]

    xfer = find_by_id token.data["id"]
    return if xfer.nil?

    repo = xfer.repository
    return if repo.nil? || repo.owner_id != token.data["oid"]

    xfer
  end

  # Public: Request an ownership change for repository. Sends an email to the
  # target (or the target's owners if it's an Organization) asking them to
  # respond to this transfer request.
  #
  # repository      - A Repository
  # target          - The User or Organization where this repo is headed
  # requester       - The User responsible for this request
  # notify          - (Optional) Send a transfer request email
  #
  # Returns a signed auth token String appropriate for self.respond().
  # Raises ActiveRecord::RecordInvalid for bad repo/target/requester combos.
  def self.start(repository, target, requester, notify = true)
    # Capture original owner for hydro event
    previous_owner = repository.owner

    # users cannot request a new name as part of a transfer that requires approval, so always default to
    # the repo name
    name_to_use = repository.name
    existing_target_repo = Repository.nwo("#{target.login_for_api}/#{name_to_use}")
    if existing_target_repo && !existing_target_repo.readable_by?(requester)
      name_to_use = Platform::Loaders::NewForkName.load(target, name_to_use).sync
    end

    xfer = create! do |x|
      x.repository      = repository
      x.requester       = requester
      x.target          = target
      x.new_name        = name_to_use
    end

    AccountMailer.repository_transfer(xfer).deliver_later if notify

    repository.instrument :transfer_start,
      requester: requester,
      target: target

    GlobalInstrumenter.instrument(
      "repository_transfer.request_start",
      { repository_transfer: xfer, previous_owner: previous_owner }
    )

    xfer.token
  end

  def self.requires_transfer_request?(target:, requester:, repository_visibility:)
    GitHub.repository_transfer_requests_enabled? && target.requires_transfer_requests_from?(requester, repository_visibility)
  end

  # Public: Immediately transfers a repo from requester to target. Sends an email
  # to the target/target's owners letting them know of the transfer.
  #
  # repository        - A Repository
  # target            - The User or Organization where this repo is headed
  # requester         - The User responsible for this request
  # target_teams      - The Teams which will be given access to this repo
  # new_name          - The new name which will be given to this repo
  # custom_properties - Custom properties to be set on the repository
  #
  # Returns nothing of consequence.
  def self.transfer_immediately(repository, target, requester, target_teams, new_name = nil, custom_properties: nil)
    if requires_transfer_request?(target: target, requester: requester, repository_visibility: repository.visibility)
      repository.errors.add(:base, "repository can't be transferred without approval from the new owner")
      return
    end

    # Capture original owner for hydro event
    previous_owner = repository.owner
    repository.async_transfer_ownership_to(
      target,
      actor: requester,
      target_teams: target_teams,
      notify_target: true,
      new_name: new_name,
      custom_properties: custom_properties,
    )

    GlobalInstrumenter.instrument(
      "repository_transfer.immediate",
      { repository: repository, requester: requester, target: target, previous_owner: previous_owner }
    )
  end

  # Public: Respond to an ownership change request for a repository. Move to
  # the `responded` state, then kick off the actual repo transfer. This record
  # will be deleted at the end of the transfer process.
  #
  # responder - The User who responded to the request
  #
  # Returns self.
  def finish(responder)
    self.responder = responder
    self.state = :responded
    # Capture original owner for hydro event
    previous_owner = self.source

    save!

    transfer_async

    GlobalInstrumenter.instrument(
      "repository_transfer.request_finish",
      { repository_transfer: self, previous_owner: previous_owner }
    )

    self
  end

  # Public: Where's this transfer coming from? The repository's current owner.
  def source
    repository.owner
  end

  # Public: A remote access token for this transfer. Pass the token to
  # RepositoryTransfer.from() to retrieve the transfer. This attribute is
  # only available in the `requested` state
  def token
    return unless requested?

    @token ||= target.signed_auth_token \
      data: { "id" => id, "oid" => repository.owner_id },
      expires: 1.day.from_now,
      scope: SCOPE
  end

  # Internal: Actually perform the repository transfer. Only called by `finish` above.
  def transfer_async
    repository.async_transfer_ownership_to target, actor: responder, new_name: new_name
  end

  protected

  # before_valdation
  # sets the new_name attribute to a reasonable default
  def set_initial_new_name
    self.new_name = repository.name if new_name.blank?
  end

  # before_action
  def repository_can_be_transferred
    unless repository.can_transfer_ownership?
      errors.add :repository, "can't be transferred"
    end

    unless RulesEngine::RepositoryActionEvaluator.can_transfer_repository?(repository, requester)
      errors.add :base, "Ruleset(s) are preventing this repository from being transferred."
    end
  end

  # before_action
  def internal_repository_must_stay_in_enterprise
    if repository.internal? && (!target&.organization? || !repository.organization.same_business_as_org?(target))
      errors.add :base, "Internal repositories can only be transferred to an organization in the enterprise"
    end
  end

  # before_action
  def requester_can_admin_repository
    unless repository.resources.administration.writable_by? requester
      errors.add :base, "#{requester} can't administer this repository"
    end
  end

  # before_action
  def requester_is_not_blocked_by_target
    if requester.blocked_by?(target)
      errors.add :base, "You can't perform that action at this time"
    end
  end

  # before_action
  def original_and_target_owners_are_different
    if repository.owner == target
      errors.add :base, "Repositories cannot be transferred to the original owner"
    end
  end

  # before_action
  def from_org_to_self
    # You can transfer a private/public repository from an org to yourself
    # internal_repository_must_stay_in_enterprise, validates that the target org is an organization for internal repos
    if !repository.internal? && transfer_from_org_to_another_user?
      errors.add :base, "You can only transfer a repository from an organization to " +
        "yourself at this time"
    end
  end

  # before_action
  def responder_can_admin_target
    unless target.adminable_by?(responder)
      errors.add :base, "#{responder} can't administer this repository"
    end
  end

  # before_action
  def target_has_no_conflicting_fork
    return unless errors.blank?
    return if target.organization?

    if target && target.has_forked?(repository)
      errors.add :base, "#{target.login_for_api} already has a repository in the" + " #{repository.root.name_with_owner_for_api} network"
    end
  end

  # before_action
  def target_has_sufficient_seats
    return if repository.public?
    return unless target
    return if target.plan.free? || target.plan.free_with_addons?
    return if target.delegate_billing_to_business? && target.business == repository.business

    required_seats = target.seats_needed_for_collaborators_on(repository)
    available_seats = if target.organization?
      target.available_invitable_seats
    else
      target.plan_limit(:collaborators, visibility: :private)
    end

    if required_seats > available_seats
      errors.add :base, "#{target.login_for_api} has insufficient collaborator seats."
    end
  end

  # before_action
  def target_can_accept_outside_collaborators
    if target&.organization? && !target&.members_can_invite_outside_collaborators?
      # add an error if any of the repository members are not an org member
      repo_has_outside_collaborators = (repository.members.pluck(:login) - target.members.pluck(:login)).size > 0

      if repo_has_outside_collaborators
        errors.add :base, "This repository has collaborators not permitted by #{target.login_for_api} organization. "\
         "To transfer the repository you will need to remove these collaborators, "\
         "or enable \"Allow repository administrators to invite outside collaborators\" in the #{target.login} organization's settings."
      end
    end
  end

  # before_action
  def repo_owner_is_not_spammy
    if repository.owner.spammy?
      GitHub.dogstats.increment("spam.repo_transfer_prohibited")
      errors.add :base, "Repository transfers not available for this account"
    end
  end

  # before_action
  def repo_not_locked_on_migration
    if repository.locked_on_migration?
      errors.add :repository, "is locked for migration"
    end
  end

  # before_action
  def target_owner_exists
    if !target || target.hide_from_user?(requester) || (GitHub.suspended_users_visible? && target.suspended?)
      errors.add :base, "Cannot find new owner '#{requested_target}'"
    end
  end

  # before_action
  def permission_on_new_org_repo
    new_is_org = target && target.organization?
    if new_is_org && !target.can_create_repository?(requester, visibility: repository.visibility)
      errors.add :base, "You don’t have the permission to create #{repository.visibility} repositories on #{target.login_for_api}"
    end
  end

  # before_action
  def target_owner_is_not_blocked_personal_namespace
    if creation_blocked_for_repo_in_personal_namespace?(requester, target)
      errors.add :base, creating_repo_in_personal_namespace_enterprise_setting_message(requester)
    end
  end

  # before_action
  def target_can_accept_repository
    return unless errors.blank?
    is_private = repository.private?
    is_fork = repository.fork?

    unless target.can_own_repositories?
      errors.add(:base, "#{target} cannot own any repositories") && return
    end

    if is_private && !is_fork && target.at_private_repo_limit?
      errors.add :base, "#{target} has no private repositories available in their subscription"
    end
  end

  # before_action
  def target_repo_does_not_exist
    return unless errors.blank?
    existing_target_repo = Repository.nwo("#{target.login_for_api}/#{new_name}")

    # we can't leak the existence of a private repo, so do not throw this error unless the requesting
    # user can see the destination repo. if the user can't see this, then the self.start method above
    # will silently change the name before the transfer is attempted.
    if existing_target_repo&.readable_by?(requester)
      errors.add :base, "#{existing_target_repo.name_with_owner_for_api} already exists"
    end
  end

  # before_action
  def org_repo_deletion_restriction
    # Rulesets that block repository deletion should not block repository transfer.
    # Instead, repository transferring is handled as an entirely separate rule.
    if error_message = DISABLED_REASON[repository.cannot_delete_or_transfer_repository_reason(requester)]
      errors.add :base, error_message
    end
  end

  # before_action
  def valid_emu_context
    source_business = repository.enterprise_managed_business
    target_business = target_enterprise_managed_business

    if source_business.nil? && target_business.present?
      # transfer from non-EMU context to EMU context
      errors.add :base, CANNOT_TRANSFER_TO_EMU_REASON + " '#{target&.login_for_api}'"
    elsif source_business != target_business
      # transfer from EMU business to different EMU business
      # or transfer from EMU context to non-EMU context
      errors.add :base, CANNOT_TRANSFER_FROM_EMU_REASON
    end
  end

  private

  # Internal: is the transfer from an organization to a user
  # other than the current user
  #
  # Returns boolean
  def transfer_from_org_to_another_user?
    new_is_org = target && target.organization?
    old_is_org = repository.owner.organization?
    new_is_stranger = target != requester

    old_is_org && !new_is_org && new_is_stranger
  end

  def dotcom?
    !GitHub.enterprise?
  end

  # Return the enterprise managed business for the target
  # Returns nil if the target is not enterprise managed
  def target_enterprise_managed_business
    if target&.organization? && target.enterprise_managed_user_enabled?
      target.business
    elsif target&.user? && target.is_enterprise_managed?
      target.enterprise_managed_business
    end
  end

  # Private: Is there a `RetiredNamespace` that transferring this repository would conflict with after transferring
  #          to the target?
  #
  # Returns a Boolean.
  def has_conflicting_retired_namespace?
    conflicting_namespace = RetiredNamespace.for(owner: target.display_login, name: repository.name)
    return false unless conflicting_namespace.present?

    !conflicting_namespace.claimable_by?(target)
  end

  def ensure_not_retired_namespace
    return unless target.present? && repository.present?
    return unless has_conflicting_retired_namespace?
    errors.add(:repository, "name #{target.login_for_api}/#{repository.name} has been retired and cannot be reused")
  end

  def valid_custom_properties
    return unless target&.organization? && custom_properties.present?
    if target.can_edit_organization_custom_properties_values?(requester)
      validation_errors = Repositories.domain.custom_properties.validate_properties(target, custom_properties)
      validation_errors.each { |error| errors.add(:base, error.error_message) }
    else
      errors.add(:base, "User does not have permission to set custom properties")
    end
  end

  def new_owner_under_repository_limit
    return unless target.present?
    limiter = RepositoryLimit.new(target)
    return unless limiter.enabled?

    return unless limiter.hard_limited?

    errors.add(:base, "New owner is over repository limit.")
  end
end
