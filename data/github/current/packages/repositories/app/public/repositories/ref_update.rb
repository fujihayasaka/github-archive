# typed: strict
# frozen_string_literal: true

module Repositories
  class RefUpdate
    include GitHub::BatchMethod
    include Pushes::CommitsHelper
    include Pushes::ChangedFilesHelper

    extend GH::RecordTransformer
    extend T::Generic

    ValueType = type_template { { fixed: Repositories::RefUpdate } }

    delegate :id, :repository_id, :push_id, :before_oid, :after_oid, :ref, :ref_update_type, to: :@attributes

    sig { override.returns(String) }
    def before
      @attributes.before_oid
    end

    sig { override.returns(String) }
    def after
      @attributes.after_oid
    end

    batch_method(:batched_repository, Repository) do |ref_updates|
      repository_ids = ref_updates.map(&:repository_id).compact.uniq
      repositories = ::Repository.where(id: repository_ids).index_by(&:id)
      ref_updates.index_with do |ref_update|
        repository_id = ref_update.repository_id
        raise ActiveRecord::RecordNotFound, "Missing repository_id for RefUpdate #{ref_update.id}" if repository_id.nil?
        repo = repositories[repository_id]
        raise ActiveRecord::RecordNotFound, "Repository not found for id #{repository_id}" unless repo
        repo
      end
    end

    # Re-define with an override sig to satisfy the abstract method from CommitsHelper/ChangedFilesHelper,
    # but call the method generated by batch_method to avoid duplicating the batching logic.
    sig { override.returns(Repository) }
    def repository
      # The alternative to this is to duplicate the method batch_method generates. This is less bad.
      public_send(:batched_repository)
    end

    sig { returns(Promise[Repository]) }
    def async_batch_repository
      public_send(:async_batch_batched_repository)
    end

    batch_method(:batched_pusher, User) do |ref_updates|
      # get pushes per unique repo, so we can issue a query per repo, avoiding cross-shard queries
      pushes = ref_updates.group_by(&:repository_id).each_with_object({}) do |(repo_id, repo_ref_updates), acc|
        push_ids = repo_ref_updates.map(&:push_id).compact.uniq
        next if repo_id.nil? || push_ids.empty?
        ::Push.where(repository_id: repo_id, id: push_ids).each { |push| acc[push.id] = push }
      end

      pusher_ids = pushes.values.map(&:pusher_id).compact.uniq
      users = ::User.where(id: pusher_ids).index_by(&:id)

      ref_updates.index_with do |ref_update|
        raise ActiveRecord::RecordNotFound, "No push_id" unless ref_update.push_id
        push = pushes[ref_update.push_id]
        raise ActiveRecord::RecordNotFound, "Push not found" unless push
        user = users[push.pusher_id]
        raise ActiveRecord::RecordNotFound, "Pusher not found" unless user
        user
      end
    end

    # Define with an override sig to satisfy the abstract method from ChangedFilesHelper,
    # but call the method generated by batch_method to avoid duplicating the batching logic.
    sig { override.returns(User) }
    def pusher
      # The alternative to this is to duplicate the method batch_method generates. This is less bad.
      public_send(:batched_pusher)
    end

    sig { returns(Promise[User]) }
    def async_batch_pusher
      public_send(:async_batch_batched_pusher)
    end

    sig { params(commits: T.nilable(T::Array[::Commit])).returns(T.nilable(T::Array[::Commit])) }
    attr_writer :commits

    sig { override.returns(T::Boolean) }
    attr_reader :spokes_api_fail_fast_enabled

    sig { params(spokes_api_fail_fast_enabled: T::Boolean).returns(T::Boolean) }
    attr_writer :spokes_api_fail_fast_enabled

    sig do
      params(
        id: T.nilable(Integer),
        push_id: T.nilable(Integer),
        repository_id: T.nilable(Integer),
        before_oid: String,
        after_oid: String,
        ref: String,
        ref_update_type: T.nilable(String),
        repository: T.nilable(Repository),
        pusher: T.nilable(User)
      ).void
    end
    def initialize(id, push_id, repository_id, before_oid, after_oid, ref, ref_update_type, repository: nil, pusher: nil)
      # We can simplify this once we've fully transitioned ref update data out of pushes and into ref_updates and the
      # ::from_args method goes away. The validations here assure consistency for callers of ::from_record(s) and ::from_args.
      # We perform them only in dev/test to help new callers succeed without introducing new failure modes in production.
      if Rails.env.development? || Rails.env.test? # rubocop:disable GitHub/DoNotBranchOnRailsEnv
        raise ArgumentError, "Must provide repository or repository_id" if repository.nil? && repository_id.nil?
        raise ArgumentError, "Repository and pusher must both be provided or both be nil" if repository.nil? ^ pusher.nil?
        raise ArgumentError, "Repository ID mismatch" if repository && repository_id && repository.id != repository_id
      end

      @attributes = T.let(RefUpdateAttributes.new(id:, push_id:, repository_id: repository_id || repository&.id,
        before_oid:, after_oid:, ref:, ref_update_type:), RefUpdateAttributes)
      @spokes_api_fail_fast_enabled = T.let(true, T::Boolean)

      @repository = T.let(repository, T.nilable(Repository))
      @pusher = T.let(pusher, T.nilable(User))
      @prelude_preloader = T.let(nil, T.nilable(Prelude::Preloader))

      unsafe_preload_batch_method_value(:batched_repository, repository) if repository
      unsafe_preload_batch_method_value(:batched_pusher, pusher) if pusher
    end

    sig { params(other: T.untyped).returns(T::Boolean) }
    def ==(other)
      !!(other.is_a?(RefUpdate) && @attributes == other.attributes)
    end

    alias_method :eql?, :==

    sig { override.returns(Integer) }
    def hash
      @attributes.hash
    end

    sig { returns(RefUpdateAttributes) }
    def attributes
      @attributes
    end

    sig { params(ref_update: T.nilable(::RefUpdate)).returns(T.nilable(RefUpdate)) }
    def self.from_record(ref_update)
      if ref_update
        new(ref_update.id, ref_update.push_id, ref_update.repository_id, ref_update.before_oid, ref_update.after_oid, ref_update.ref, ref_update.ref_update_type)
      else
        nil
      end
    end

    sig { override.params(ref_updates: T::Array[T.nilable(::RefUpdate)]).returns(T::Array[RefUpdate]) }
    def self.from_records(ref_updates)
      r = ref_updates.map do |ref_update|
        from_record(ref_update)
      end
      result = r.compact
      Prelude.wrap(result) # to ensure batch methods work on the resulting array of RefUpdate objects
      result
    end

    sig do
      params(
        before: String,
        after: String,
        ref: String,
        repository: Repository,
        pusher: User
      ).returns(Repositories::RefUpdate)
    end
    def self.from_args(before:, after:, ref:, repository:, pusher:)
      new(nil, nil, repository.id, before, after, ref, nil, repository:, pusher:)
    end

    sig { returns(T::Boolean) }
    def pages_branch?
      ref == "refs/heads/#{repository.pages_branch}"
    end

    sig { returns(T::Boolean) }
    def default_branch?
      ref == "refs/heads/#{repository.default_branch}"
    end

    sig { returns(T::Boolean) }
    def initial_commit?
      created? && !deleted?
    end

    # whether or not we'll store a record for this ref update
    sig { returns(T::Boolean) }
    def recordable?
      return false if is_note?
      return false if ref_is_tag? && !deleted?
      branch_or_tag?
    end

    sig { params(attr_name: T.untyped).returns(T.untyped) }
    def [](attr_name)
      @attributes.public_send(attr_name) if @attributes.members.include?(attr_name.to_sym) # rubocop:disable GitHub/AvoidObjectSendWithDynamicMethod
    end
  end
end
