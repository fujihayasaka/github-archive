  test "expected dependencies" do
    dependencies = clean_dependencies(Repository.included_modules.map(&:name).sort)
    assert_equal @known_dependencies, dependencies, "Unexpected module included in Repository, reach out to #repos-platform before you add more"
  end

  test "expected dependencies are sorted" do
    assert_equal @known_dependencies, @known_dependencies.sort
  end

  test "expected assocations" do
    # In most cases you can avoid the assocation by using `NewModel.where(repository_id: repo.id)` instead of `repo.new_model`
    # or using `destroy_in_background_with :repository` in `NewModel` instead of `has_many :new_models, dependent: :destroy` in `Repository`.
    associations = Repository.reflect_on_all_associations.map(&:name).sort
    assert_equal @known_assocations, associations, "Unexpected assocation found in Repository, reach out to #repos-platform before you add more"
  end

  test "expected assocations are sorted" do
    assert_equal @known_assocations, @known_assocations.sort
  end

  test "expected callbacks" do
    assert_equal @known_callbacks, callbacks, "Unexpected callback included in Repository, reach out to #repos-platform before you add more"
  end

  test "expected callbacks by type" do
    tally = {
      [:after, :commit] => 13,
      [:after, :create] => 6,
      [:after, :destroy] => 7,
      [:after, :save] => 2,
      [:around, :save] => 1,
      [:before, :create] => 2,
      [:before, :destroy] => 41,
      [:before, :save] => 2
    }
    assert_equal tally, callbacks(include_procs: true).map { |c| [c.first, c.second] }.tally, "Unexpected callback included in Repository, reach out to #repos-platform before you add more"
  end

  test "expected callbacks are sorted" do
    assert_equal @known_callbacks, @known_callbacks.sort
  end

  def callbacks(include_procs: false)
    chains = [
      Repository._create_callbacks,
      Repository._save_callbacks,
      Repository._update_callbacks,
      Repository._destroy_callbacks,
      Repository._commit_callbacks,
    ]
    callbacks = chains.flat_map(&:to_a).map do |chain|
      [chain.kind, chain.name, chain.filter.is_a?(Proc) ? :proc : chain.filter]
    end.reject do |chain|
      (!include_procs && chain.third == :proc) || chain.third.start_with?("autosave_associated_records_for")
    end.sort
  end

  def clean_dependencies(list)
    list - @excluded_dependencies
  end
