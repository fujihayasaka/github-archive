# rubocop:disable Metrics/MethodLength
# typed: strict
# frozen_string_literal: true

require "sweagentd"
require "monolith-twirp-copilot-mission-control-tasks"

module Issues
  class Domain
    class Triage < GH::Domain::Base

      TRIAGE_AGENT_FOOTER_BASE_TEXT = T.let("Generated by Copilot Triage Agent".freeze, String)

      # Roles that are allowed to perform management actions for the triage agent (maintain and above)
      MANAGEMENT_ROLES = T.let([:maintain, :admin].freeze, T::Array[Symbol])

      # Roles that are allowed to invoke retriage (triage and above)
      RETRIAGE_ROLES = T.let([:triage, :write, :maintain, :admin].freeze, T::Array[Symbol])

      # Check if a user has the required role (maintain+) to manage the triage agent on a repository.
      # This gates UI configuration for managing the triage agent, not necessarily
      # the enable/disable toggle endpoint itself.
      sig { params(user: T.nilable(User), repository: Repository).returns(T::Boolean) }
      def can_manage_triage_agent?(user, repository)
        check_triage_agent_role(user, repository, action: :manage, allowed_roles: MANAGEMENT_ROLES)
      end

      # Check if a user has the required role (triage+) to invoke retriage on a repository.
      sig { params(user: T.nilable(User), repository: Repository).returns(T::Boolean) }
      def can_invoke_retriage?(user, repository)
        check_triage_agent_role(user, repository, action: :retriage, allowed_roles: RETRIAGE_ROLES)
      end

      # Triggers a triage agent job for the given issue via the Twirp Jobs API.
      # This creates a Copilot job that will analyze and triage the issue.
      # When problem_statement or triage_prompt are provided (debug mode), they override the
      # auto-generated defaults.
      sig { params(issue: Issue, repository: Repository, type: T.nilable(Symbol), comment: T.nilable(IssueComment), problem_statement: T.nilable(String), triage_prompt: T.nilable(String), actor: T.nilable(User)).void }
      def trigger_triage_agent_job_twirp(issue:, repository:, type: :triage, comment: nil, problem_statement: nil, triage_prompt: nil, actor: nil)
        actor = actor || issue.user
        return unless actor

        owner_id = repository.owner_id
        if owner_id.nil?
          raise ArgumentError, "Failed to create triage agent job: repository owner is nil"
        end

        # Normalize blank overrides to nil so that debug detection and ||= behave correctly
        problem_statement = problem_statement&.presence
        triage_prompt = triage_prompt&.presence

        has_problem_statement_override = problem_statement && !problem_statement.strip.empty?
        has_triage_prompt_override = triage_prompt && !triage_prompt.strip.empty?
        is_debug = has_problem_statement_override || has_triage_prompt_override

        # Generate a problem statement based on triage type (unless provided for debug)
        # The agent can use MCP to fetch additional details if needed
        problem_statement ||= TriageAgent::PromptBuilder.generate_triage_problem_statement(issue: issue, type: type, comment: comment)

        # Generate the triage agent prompt with identity, flow, formatting, and output format
        # This is passed separately via custom_agent_attributes.prompt
        triage_prompt ||= TriageAgent::PromptBuilder.generate_triage_agent_prompt(repository: repository)

        # Add eyes emoji reaction to indicate triage is in progress
        copilot_bot = get_copilot
        subject = type == :retriage && comment ? comment : issue
        Issues.domain.reactions.add_eyes(subject, copilot_bot) if copilot_bot

        use_mission_control = IssuesTriageAgentFeature.use_mission_control?(repository)
        method_tag = if is_debug
          use_mission_control ? "mission_control_debug" : "twirp_debug"
        else
          use_mission_control ? "mission_control" : "twirp"
        end

        if IssuesTriageAgentFeature.fake_triage_enabled?
          submit_local_dev_triage_suggestions(issue: issue, mode: method_tag, prompt: triage_prompt, problem_statement: problem_statement)
        elsif use_mission_control
          trigger_via_mission_control(
            issue: issue, repository: repository, actor: actor,
            owner_id: owner_id, problem_statement: problem_statement,
            triage_prompt: triage_prompt, method_tag: method_tag
          )
        else
          trigger_via_sweagentd(
            issue: issue, repository: repository, actor: actor,
            owner_id: owner_id, problem_statement: problem_statement,
            triage_prompt: triage_prompt, method_tag: method_tag
          )
        end
      rescue GitHub::Sweagentd::Client::Jobs::Error => e
        Issues.domain.reactions.remove_eyes(subject: subject, user_ids: [copilot_bot.id]) if copilot_bot
        log_and_track("triage_agent.job_creation_failed",
          level: :error,
          actor: actor,
          repository: repository,
          issue: issue,
          dd_tags: ["success:false", "method:#{method_tag}", "reason:job_creation_error"],
          log_extra: {
            "method" => method_tag,
            "error" => e.message,
          })
        Failbot.report(e, {
          app: "github",
          feature: "triage_agent",
          context: "job_creation_twirp"
        })
      rescue GitHub::CopilotMissionControl::Client::Tasks::Error => e
        Issues.domain.reactions.remove_eyes(subject: subject, user_ids: [copilot_bot.id]) if copilot_bot
        log_and_track("triage_agent.job_creation_failed",
          level: :error,
          actor: actor,
          repository: repository,
          issue: issue,
          dd_tags: ["success:false", "method:#{method_tag}", "reason:job_creation_error"],
          log_extra: {
            "method" => method_tag,
            "error" => e.message,
          })
        Failbot.report(e, {
          app: "github",
          feature: "triage_agent",
          context: "job_creation_mission_control"
        })
      end

      # Checks whether a triage agent config file exists in the repository's default branch.
      # Used by orchestration guards to enforce mandatory config when the feature flag is enabled.
      sig { params(repository: Repository).returns(T::Boolean) }
      def config_file_exists?(repository)
        return false if repository.access.broken?

        default_branch_ref = repository.default_branch_ref
        return false unless default_branch_ref

        blob = repository.blob(default_branch_ref.target_oid, TriageAgent::Configuration::CONFIG_FILE_PATH)
        blob&.data.present?
      rescue GitRPC::Error, Repository::CorruptionDetected
        false
      end

      # Determines if an operation on an issue should be treated as retriage vs initial triage.
      # Returns true if the issue already has triage comments from the Copilot bot.
      # Returns false for new issues or issues that haven't been triaged yet.
      sig { params(issue: Issue).returns(T::Boolean) }
      def retriage_operation?(issue)
        copilot_bot = get_copilot
        return false unless copilot_bot

        # Check if there are any comments from the copilot bot that contain the triage footer
        # Use Ruby's include? method which properly handles encoding and special characters
        issue.comments.where(repository: issue.repository_id, user: copilot_bot).any? do |comment|
          comment.body.include?(TRIAGE_AGENT_FOOTER_BASE_TEXT)
        end
      end

      private

      # Shared role check for triage agent permissions. Logs when access is denied.
      sig { params(user: T.nilable(User), repository: Repository, action: Symbol, allowed_roles: T::Array[Symbol]).returns(T::Boolean) }
      def check_triage_agent_role(user, repository, action:, allowed_roles: MANAGEMENT_ROLES)
        return false if user.nil?

        role = repository.async_action_or_role_level_for(user, include_custom_roles: false).sync
        allowed = role.present? && role.in?(allowed_roles)

        unless allowed
          log_and_track("triage_agent.permission_denied",
            actor: user,
            repository: repository,
            log_extra: {
              "action" => action,
              "resolved_role" => role.to_s,
            })
        end

        allowed
      end

      # Submits fake triage suggestions for local development testing.
      sig { params(issue: Issue, mode: String, prompt: String, problem_statement: T.nilable(String)).void }
      def submit_local_dev_triage_suggestions(issue:, mode:, prompt:, problem_statement: nil)
        body = <<~BODY
          This is a test triage comment for testing purposes only
          * mode: #{mode}

          * problem statement:
          ```
          #{problem_statement}
          ```
          * prompt used:

          ```
          #{prompt}
          ```
        BODY

        suggestions = Issues::Domain::Suggestions::TriageSuggestions.new(
          body: body,
          labels: [],
          type: "Feature",
          fields: []
        )
        Issues.domain.suggestions.suggest(issue: issue, suggestions: suggestions)
      end

      # Triggers a triage job via the mission-control Twirp API.
      sig do
        params(
          issue: Issue,
          repository: Repository,
          actor: User,
          owner_id: Integer,
          problem_statement: String,
          triage_prompt: String,
          method_tag: String
        ).void
      end
      def trigger_via_mission_control(issue:, repository:, actor:, owner_id:, problem_statement:, triage_prompt:, method_tag:)
        custom_agent_attributes = CopilotMissionControl::TasksAPI::V1::CustomAgentAttributes.new(
          display_name: "Issue Triage Agent",
          description: "Triage a given issue",
          prompt: triage_prompt,
          tools: ["github/*"],
          permissions: { "issues" => "write" },
          mcp_servers: mission_control_mcp_server_config(repository: repository, issue: issue),
        )

        create_task_request = CopilotMissionControl::TasksAPI::V1::CreateTaskRequest.new(
          actor_id: actor.id,
          repo_id: repository.id,
          owner_id: owner_id,
          problem_statement: problem_statement,
          event_url: issue.url,
          event_identifiers: ["issue::#{issue.number}", "issue_id::#{issue.id}"],
          event_type: "triage",
          custom_agent_attributes: custom_agent_attributes,
        )

        tasks_client = GitHub::CopilotMissionControl::Client.tasks
        response = tasks_client.create_task(create_task_request)

        # Create AgentAssignment for issue page visibility (task panel + sidebar)
        task_id = response.data&.task_id
        if task_id.present? && IssuesTriageAgentFeature.agent_assignment_enabled?(repository)
          create_triage_agent_assignment(issue: issue, actor: actor, task_id: task_id)
        end

        log_and_track("triage_agent.job_created",
          actor: actor,
          repository: repository,
          issue: issue,
          dd_tags: ["success:true", "method:#{method_tag}"],
          log_extra: {
            "method" => method_tag,
            "task_id" => task_id,
            "session_id" => response.data&.session_id,
          })
      end

      # Triggers a triage job via the sweagentd Twirp API (legacy path).
      sig do
        params(
          issue: Issue,
          repository: Repository,
          actor: User,
          owner_id: Integer,
          problem_statement: String,
          triage_prompt: String,
          method_tag: String
        ).void
      end
      def trigger_via_sweagentd(issue:, repository:, actor:, owner_id:, problem_statement:, triage_prompt:, method_tag:)
        custom_agent_attributes = Sweagentd::JobsAPI::V1::CustomAgentAttributes.new(
          display_name: "Issue Triage Agent",
          description: "Triage a given issue",
          prompt: triage_prompt,
          tools: ["github/*"],
          permissions: { "issues" => "write" },
          mcp_servers: github_mcp_server_config(repository: repository, issue: issue),
        )

        create_job_request = Sweagentd::JobsAPI::V1::CreateJobRequest.new(
          actor_id: actor.id,
          repo_id: repository.id,
          owner_id: owner_id,
          problem_statement: problem_statement,
          event_url: issue.url,
          event_identifiers: ["issue::#{issue.number}", "issue_id::#{issue.id}"],
          custom_agent_attributes: custom_agent_attributes,
          features: Sweagentd::JobsAPI::V1::Features.new
        )

        jobs_client = GitHub::Sweagentd::Client.jobs
        response = jobs_client.create_job(create_job_request)

        log_and_track("triage_agent.job_created",
          actor: actor,
          repository: repository,
          issue: issue,
          dd_tags: ["success:true", "method:#{method_tag}"],
          log_extra: {
            "method" => method_tag,
            "job_id" => response.data&.job_id,
            "session_id" => response.data&.session_id,
          })
      end

      # Returns the GitHub MCP server configuration for the CCA triage agent (sweagentd proto types).
      sig { params(repository: Repository, issue: Issue).returns(T::Hash[String, Sweagentd::JobsAPI::V1::MCPServer]) }
      def github_mcp_server_config(repository:, issue:)
        mcp_headers = {
          "X-MCP-Toolsets" => "context,issues,issue_triage,semantic_issues_search",
          "X-Triage-Issue-Target" => "#{repository.owner_display_login}/#{repository.name}##{issue.number}"
        }

        {
          "github-mcp-server" => Sweagentd::JobsAPI::V1::MCPServer.new(
            type: "http",
            url: "#{GitHub.copilot_api_internal_url}/mcp",
            tools: %w[
              get_label
              issue_read
              triage_issue
              semantic_issues_search
            ],
            headers: mcp_headers
          )
        }
      end

      # Returns the GitHub MCP server configuration using mission-control proto types.
      sig { params(repository: Repository, issue: Issue).returns(T::Hash[String, CopilotMissionControl::TasksAPI::V1::MCPServer]) }
      def mission_control_mcp_server_config(repository:, issue:)
        mcp_headers = {
          "X-MCP-Toolsets" => "context,issues,issue_triage,semantic_issues_search",
          "X-Triage-Issue-Target" => "#{repository.owner_display_login}/#{repository.name}##{issue.number}"
        }

        {
          "github-mcp-server" => CopilotMissionControl::TasksAPI::V1::MCPServer.new(
            type: "http",
            url: "#{GitHub.copilot_api_internal_url}/mcp",
            tools: %w[
              get_label
              issue_read
              triage_issue
              semantic_issues_search
            ],
            headers: mcp_headers
          )
        }
      end

      # Centralized logging helper that both logs to the logger and increments a Datadog counter.
      # Common fields (actor_id/actor_login, repository_id/repository_nwo, issue_id/issue_number)
      # are automatically included when the corresponding objects are provided.
      sig do
        params(
          event: String,
          level: Symbol,
          actor: T.nilable(User),
          repository: T.nilable(Repository),
          issue: T.nilable(Issue),
          dd_tags: T::Array[String],
          log_extra: T::Hash[String, T.untyped]
        ).void
      end
      def log_and_track(event, level: :info, actor: nil, repository: nil, issue: nil, dd_tags: [], log_extra: {})
        GitHub.dogstats.increment(event, tags: dd_tags)

        payload = T.let({ "code.namespace" => "Issues::Domain::Triage" }, T::Hash[String, T.untyped])
        if actor
          payload["actor_id"] = actor.id
          payload["actor_login"] = actor.display_login
        end
        if repository
          payload["repository_id"] = repository.id
          payload["repository_nwo"] = repository.name_with_display_owner
        end
        if issue
          payload["issue_id"] = issue.id
          payload["issue_number"] = issue.number
        end
        payload.merge!(log_extra)

        case level
        when :error
          GitHub.logger.error(event, payload)
        else
          GitHub.logger.info(event, payload)
        end
      end

      # Creates an AgentAssignment record linking a triage task to the issue.
      # This makes the triage session visible on the issue page (task panel + sidebar assignees).
      # Failures are logged but do not block triage execution.
      sig { params(issue: Issue, actor: User, task_id: String).returns(T.nilable(AgentAssignment)) }
      def create_triage_agent_assignment(issue:, actor:, task_id:)
        copilot_bot = get_copilot
        return unless copilot_bot

        assignment = ActiveRecord::Base.connected_to(role: :writing) do
          AgentAssignment.create(
            source_repository: issue.repository,
            source_type: :issue,
            source_id: issue.id,
            assignee: copilot_bot,
            assigner: actor,
            task_id: task_id,
          )
        end

        unless assignment.persisted?
          log_and_track("triage_agent.agent_assignment_failed",
            level: :error,
            actor: actor,
            repository: issue.repository,
            issue: issue,
            dd_tags: ["success:false"],
            log_extra: {
              "task_id" => task_id,
              "errors" => assignment.errors.full_messages.join(", "),
            })
          Failbot.report(
            StandardError.new("Failed to create triage AgentAssignment: #{assignment.errors.full_messages.join(', ')}"),
            app: "github",
            feature: "triage_agent",
            context: "create_agent_assignment",
          )
        end

        assignment
      rescue StandardError => e
        log_and_track("triage_agent.agent_assignment_failed",
          level: :error,
          actor: actor,
          repository: issue.repository,
          issue: issue,
          dd_tags: ["success:false", "reason:exception"],
          log_extra: {
            "task_id" => task_id,
            "error" => e.message,
          })
        Failbot.report(e, {
          app: "github",
          feature: "triage_agent",
          context: "create_agent_assignment",
        })
        nil
      end

      sig { returns(T.nilable(Bot)) }
      def get_copilot
        app = T.let(Apps::Privileged.integration(:copilot_swe_agent), T.nilable(Integration))
        app&.bot
      end
    end
  end
end

