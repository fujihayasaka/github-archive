# typed: strict
# frozen_string_literal: true

class IssueSummary
  # Represents the state of an issue summary's summary generation.
  module State
    extend T::Helpers

    requires_ancestor { IssueSummary }

    Pending = "pending"
    Scheduled = "scheduled"
    InProgress = "in_progress"
    Complete = "complete"
    Failed = "failed"

    sig { returns(String) }
    def self.initial_state
      Pending
    end

    # If true, the summary record has been created, but is not yet scheduled for
    # generation.
    sig { returns(T::Boolean) }
    def pending?
      state == Pending
    end

    # If true, the summary is scheduled for generation.
    sig { returns(T::Boolean) }
    def scheduled?
      state == Scheduled
    end

    # If true, the summary is currently being generated by a worker.
    sig { returns(T::Boolean) }
    def in_progress?
      state == InProgress
    end

    # If true, the summary has been generated and is ready to be read by a user.
    sig { returns(T::Boolean) }
    def complete?
      state == Complete
    end

    # If true, the summary generation failed.
    sig { returns(T::Boolean) }
    def failed?
      state == Failed
    end

    class StateError < Exception; end

    # Mark the summary as scheduled and save it.
    sig { void }
    def transition_scheduled!
      unless [State::Pending, State::Failed, State::Scheduled].include?(state)
        raise StateError, "Cannot transition from #{self.state} to #{State::Scheduled}"
      end

      self.update!(state: State::Scheduled)
    end

    # Mark the summary as in progress and save it.
    sig { void }
    def transition_in_progress!
      unless [State::Scheduled, State::InProgress,].include?(state)
        raise StateError, "Cannot transition from #{self.state} to #{State::InProgress}"
      end

      self.update!(state: State::InProgress)
    end

    # Mark the summary as complete and save it.
    sig { void }
    def transition_complete!
      unless [State::InProgress, State::Complete].include?(state)
        raise StateError, "Cannot transition from #{self.state} to #{State::Complete}"
      end

      self.update!(state: State::Complete)
    end

    # Mark the summary as failed and save it.
    sig { void }
    def transition_failed!
      unless [State::InProgress, State::Failed].include?(state)
        raise StateError, "Cannot transition from #{self.state} to #{State::Failed}"
      end

      self.update!(state: State::Failed)
    end
  end
end
