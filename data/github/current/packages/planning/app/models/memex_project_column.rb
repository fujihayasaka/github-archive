  # Returns a read-only list of MemexProjectColumn objects representing those
  # that should be included by default in a brand new memex.
  #
  # This method does is NOT guaranteed to produce identical results with each
  # invocation. For example, the generated ID of a `single_select` column's
  # options may change.
  #
  # excluding - Array<String> for the names of columns that should be excluded
  #   from the returned set of default columns. This can be used to omit a new
  #   column as part of a progressive rollout.
  #
  # Returns Array<MemexProjectColumn>.
  sig { params(excluding: T::Array[String]).returns(T::Array[MemexProjectColumn]) }
  def self.default_columns(excluding: [])
    defaults = SYSTEM_DEFINED_COLUMNS.reject { |c| excluding.include?(c[:name]) }
    defaults.each_with_index.map do |params, index|
      record = self.new(params.merge(user_defined: false, position: index + 1))
      record.normalize_settings
      record.readonly!
      record
    end
  end

  def self.default_column(name, excluding: [])
    default_columns(excluding: excluding).find { |c| c.name == name }
  end

