  def sync_iteration_column_completed_iterations
    return unless iteration?
    return if settings_iterations.empty? && settings_completed_iterations.empty?

    current_settings = settings || {}
    # this method ensures that iterations are correctly ordered, deduplicated,
    # and in the correct buckets vis-a-vis completed status
    normalize_settings
    if @normalized_settings
      normalized_settings_serialized = @normalized_settings.serialize
      log_sync do
        next :skip if normalized_settings_serialized == current_settings
        update!(settings: normalized_settings_serialized)
      end
    end
  end

  private def log_sync
    result = yield
    GitHub.dogstats.increment(
      "memex_project_column.sync_iteration_column_completed_iterations",
      tags: ["skipped:#{result == :skip}"]
    )
  end

