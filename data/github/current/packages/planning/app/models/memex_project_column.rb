  # The serializable ID of this column.
  #
  # For user-defined columns, this will be the ID of the column's row in the
  # database. For system-defined columns, this will be the (reserved) name of
  # the column.
  #
  # Return Integer or String.
  def synthetic_id
    user_defined? ? id : name
  end

  def to_hash(items: [], require_prefilled_associations: true, prefilled_associations: nil, redacted_issue_ids: [])
    result = {
      dataType: data_type.camelize(:lower),
      id: synthetic_id,
      databaseId: id,
      name: name,
      nameSlug: name_slug,
      position: position,
      userDefined: user_defined,
      visible: visible,
      settings: camelized_settings,
      partialFailures: prefilled_associations&.partial_failures(synthetic_id)
    }.tap do |h|
      h[:defaultColumn] = default_column? if new_record?
    end

    column_values = items.reduce([]) do |values, item|
      val = item.column_values(
        columns: [self],
        require_prefilled_associations: require_prefilled_associations,
        prefilled_associations: prefilled_associations,
        redacted_issue_ids: redacted_issue_ids
      )[0][:value]
      values << { memexProjectItemId: item.id, value: val } if val.present?
      values
    end

    result[:memexProjectColumnValues] = column_values if column_values.present?
    result
  end

