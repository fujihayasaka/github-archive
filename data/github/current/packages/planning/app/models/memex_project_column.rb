  # When names is nil then this method will return all option IDs (current default implementation.)
  # When names is not nil then only options that match the names will be returned.
  def settings_option_ids(names = nil)
    return [] unless single_select?

    # Ensure we are comparing downcased names to downcased names
    # The null-coalescing operator (&.) will short-circuit and return nil if titles is nil
    names = names&.map(&:downcase)&.to_set

    settings_options
      .select { |o| names.nil? || names.include?(o["name"].downcase) }
      .map { |o| o["id"] }
  end

