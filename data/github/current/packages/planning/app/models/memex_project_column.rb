  def camelized_settings
    return @camelized_settings if defined?(@camelized_settings)

    @camelized_settings = if settings && settings["options"]
      camelized_settings = settings.deep_dup
      camelized_settings["options"].each do |o|
        o["nameHtml"] = o.delete("name_html")
        # Projects not modified since color & description were added will not have these fields yet
        o["descriptionHtml"] = o.delete("description_html") || ""
        o["description"] = o["description"] || ""
        o["color"] = o["color"] || MemexProjectColumn::Settings::OptionEntry::DEFAULT_COLOR
      end
      camelized_settings

    elsif settings && settings["configuration"]
      return @camelized_iteration_settings if defined?(@camelized_iteration_settings)
      camelized_iteration_settings = settings.deep_dup
      camelized_configuration = camelized_iteration_settings["configuration"]

      camelized_configuration["startDay"] = camelized_configuration.delete("start_day")
      camelized_configuration["completedIterations"] = camelized_configuration.delete("completed_iterations")
      camelized_configuration["iterations"] = (camelized_configuration["iterations"] || [])
        .map do |i|
          h = Settings::Iteration.new(i.with_indifferent_access).attributes
          h.deep_transform_keys { |k| k.to_s.camelize(:lower) }
        end
      camelized_configuration["completedIterations"] = (camelized_configuration["completedIterations"] || [])
        .map do |i|
          h = Settings::Iteration.new(i.with_indifferent_access).attributes
          h.deep_transform_keys { |k| k.to_s.camelize(:lower) }
        end
      @camelized_iteration_settings = camelized_iteration_settings

    elsif settings && settings["progress_configuration"]
      return @camelized_progress_settings if defined?(@camelized_progress_settings)
      @camelized_progress_settings = settings.deep_dup.deep_transform_keys { |key| key.camelize(:lower) }

    else
      settings
    end
  end

  def name_is_not_reserved
    return unless changed_attributes.keys.include?("name")
    return unless user_defined?

    reserved_columns = self.class.reserved_column_names(actor: actor, owner: memex_project&.owner)

    if reserved_columns.any? { |r| r.casecmp?(name) }
      errors.add(:name, "cannot have a reserved value")
    end
  end

  def name_does_not_contain_reserved_characters
    return unless changed_attributes.keys.include?("name")
    return unless user_defined?

    if RESERVED_COLUMN_NAME_CHARACTERS.any? { |c| name.include?(c) }
      characters = RESERVED_COLUMN_NAME_CHARACTERS.join(", ")
      errors.add(:name, "cannot contain any of the following characters: #{characters}")
    end
  end

  def creator_has_verified_email
    return unless GitHub.email_verification_enabled?

    return unless user_defined?

    return if creator&.bot?

    errors.add(:creator, "must have a verified email address") unless creator&.verified_emails?
  end

  def default_columns_persisted
    return unless user_defined?

    unless memex_project&.memex_project_columns&.any?(&:system_defined?)
      errors.add(:user_defined, "column cannot be added until default columns have been persisted")
    end
  end

  def column_can_be_created
    return unless (project = memex_project)

    if project.memex_project_columns.count >= MemexProject::COLUMN_LIMIT
      errors.add(:base, "Projects cannot have more than #{MemexProject::COLUMN_LIMIT} fields, including default and custom fields")
    end
  end

  def name_is_not_changing
    if changed_attributes.keys.include?("name")
      errors.add(:name, "cannot be changed for a system defined column")
    end
  end

  def instrument_creation_event
    # system defined columns are created by the system, so don't need to be tracked to an actor
    return unless user_defined?

    GlobalInstrumenter.instrument "memex_event", {
      actor: actor,
      memex_project: memex_project,
      memex_project_column: self,
      performed_at: Time.current,
      name: ON_CREATE_INSTRUMENTATION_KEY
    }
    instrument :create, prefix: "project_field"
  end

  def instrument_update_event
    GlobalInstrumenter.instrument "memex_project_column.update", {
      actor: actor,
      memex_project: memex_project,
      memex_project_column: self,
      performed_at: Time.current,
    }
    instrument :update, prefix: "project_field"
  end

  def instrument_deletion
    GlobalInstrumenter.instrument "memex_project_column.delete", {
      actor: actor,
      memex_project: memex_project,
      memex_project_column: self,
      performed_at: Time.current,
    }
    instrument :delete, prefix: "project_field"
  end

  def event_payload
    payload = {
      project_field: self,
      project_number: memex_project&.number,
      project: memex_project,
      public_project: memex_project&.public?,
      actor: actor,
      performed_at: Time.current,
    }.tap do |p|
      owner = memex_project&.owner

      p[owner.event_prefix] = owner if owner
    end
    payload
  end

  # Dig out previous options, if any. Represent the state of no previous
  # options with an empty array, for return type consistency.
  #
  # Returns Array
  def previous_options
    self.previous_changes.dig("settings", 0, "options") || []
  end

  # Designed to run after commit (or other event where we don't yet know what
  # kind of column we're dealing with), this checks to see if the options for
  # a single-select column changed.
  #
  # Returns Boolean
  def options_changed?
    return false unless self.single_select?
    return false unless self.previous_changes["settings"]
    return false if previous_options.empty?
    true
  end

  # Designed to run after commit, this derives the ids of any options that were
  # removed from a single-select column's settings.
  #
  # Returns Array<String>
  def diff_options_removed
    previous_option_ids = previous_options.map { |o| o["id"] }
    diff = previous_option_ids - settings_option_ids
    diff
  end

  def remove_deleted_single_select_values
    return false unless options_changed?
    removed_option_ids = diff_options_removed
    RemoveMemexProjectColumnValuesJob.perform_later(self.id, removed_option_ids)
  end

  # When an option is removed from a single-select column's settings, we may
  # need to update workflows and/or workflow actions that were configured to
  # use the option that has now been deleted.
  #
  # Returns nothing
  def update_workflow_actions
    return unless options_changed?

    removed_option_ids = diff_options_removed
    return if removed_option_ids.empty?
    DisableMemexWorkflowsWithInvalidOptionJob.perform_later(column_id: self.id, removed_option_ids: removed_option_ids)
  end

  def user_defined_type_column_is_renamed?
    user_defined? && name_previously_changed? && name_previously_was.casecmp?(MemexProjectColumn::TYPE_COLUMN_NAME)
  end

  def user_defined_type_column_is_destroyed?
    destroyed? && user_defined? && name.casecmp?(MemexProjectColumn::TYPE_COLUMN_NAME)
  end

  def backfill_system_defined_type_column
    return unless (project = memex_project)
    return unless project.org_owned?

    issue_type_column = project.backfill_issue_type_column

    if issue_type_column.persisted? && issue_type_column.previously_new_record?
      GitHub.dogstats.increment("memex_project_column.backfill_issue_type_column", tags: ["result:success"])
    elsif issue_type_column.invalid?
      GitHub.dogstats.increment("memex_project_column.backfill_issue_type_column", tags: ["result:error"])
      errors.add(:base, :issue_type_column_backfill_failed)

      # Report a custom user error to monitor errors backfilling system-defined Type column
      err = IssueTypeColumnBackfillError.new(issue_type_column)
      Failbot.report_user_error(err, memex_project_id: project.id)

      raise ActiveRecord::Rollback
    end
  end

  def remove_deleted_iteration_values
    return unless self.iteration?
    return unless self.previous_changes.dig("settings")
    # If there were no previous iterations, there's nothing to clean up
    return unless previous_iterations = self.previous_changes.dig("settings", 0, "configuration", "iterations")
    return unless previous_completed_iterations = self.previous_changes.dig("settings", 0, "configuration", "completed_iterations")

    # handle cases where any of these values are nil and ensure an array is returned
    candidate_iterations = [previous_iterations, previous_completed_iterations].compact.reduce([], :|)
    previous_iteration_ids = candidate_iterations.map { |o| o["id"] }

    RemoveMemexProjectColumnValuesJob.perform_later(self.id, (previous_iteration_ids - settings_iteration_ids - settings_completed_iteration_ids))
  end

  def remove_view_visibility
    return unless memex_project
    memex_project&.memex_project_views&.map { |view| view.remove_column!(self) }
  end
