# typed: true
# frozen_string_literal: true

require "test_helper"

class Billing::PlanSubscription::ZuoraRatePlanChargeTest < GitHub::BillingTestCase

  context ".reconcile" do
    test "adds active charges from zuora to the plan subscription's zuora charges table" do
      plan_subscription = create(:billing_plan_subscription, :zuora)
      charge = build(:zuora_rate_plan_charge)

      assert_difference "Billing::PlanSubscription::ZuoraRatePlanCharge.count", 1 do
        Billing::PlanSubscription::ZuoraRatePlanCharge.reconcile(
          plan_subscription: plan_subscription,
          active_charges_from_zuora: [charge]
        )
      end

      assert_equal 1, plan_subscription.subscription_rate_plan_charges.count
      assert_equal charge.to_h, plan_subscription.subscription_rate_plan_charges.first.payload

      assert_no_difference "Billing::PlanSubscription::ZuoraRatePlanCharge.count" do
        Billing::PlanSubscription::ZuoraRatePlanCharge.reconcile(
          plan_subscription: plan_subscription,
          active_charges_from_zuora: [charge]
        )
      end
    end

    test "updates existing charges in the plan subscription if the payloads are different" do
      plan_subscription = create(:billing_plan_subscription, :zuora)
      charge = build(:zuora_rate_plan_charge)
      different_payload = charge.to_h
      different_payload["quantity"] = charge.quantity + 10
      current_charge = create(
        :plan_subscription_zuora_rate_plan_charge,
        plan_subscription: plan_subscription,
        payload: different_payload
      )
      refute_equal charge.to_h, current_charge.payload

      assert_no_difference "Billing::PlanSubscription::ZuoraRatePlanCharge.count" do
        Billing::PlanSubscription::ZuoraRatePlanCharge.reconcile(
          plan_subscription: plan_subscription,
          active_charges_from_zuora: [charge]
        )
      end

      assert_equal 1, plan_subscription.subscription_rate_plan_charges.count
      assert_equal charge.to_h, plan_subscription.subscription_rate_plan_charges.first.payload
      assert_equal charge.to_h, current_charge.reload.payload
    end

    test "destroys zuora rate plan charge records when they are not found in the active list" do
      plan_subscription = create(:billing_plan_subscription, :zuora)
      create(
        :plan_subscription_zuora_rate_plan_charge,
        plan_subscription: plan_subscription,
      )

      assert_difference "Billing::PlanSubscription::ZuoraRatePlanCharge.count", -1 do
        Billing::PlanSubscription::ZuoraRatePlanCharge.reconcile(
          plan_subscription: plan_subscription,
          active_charges_from_zuora: []
        )
      end

      assert_equal 0, plan_subscription.subscription_rate_plan_charges.count
    end

    test "removes duplicate zuora rate plan charge records" do
      plan_subscription = create(:billing_plan_subscription, :zuora)
      charge = build(:zuora_rate_plan_charge)
      create(
        :plan_subscription_zuora_rate_plan_charge,
        plan_subscription: plan_subscription,
        payload: charge.to_h
      )
      create(
        :plan_subscription_zuora_rate_plan_charge,
        plan_subscription: plan_subscription,
        payload: charge.to_h
      )

      assert_equal 2, plan_subscription.subscription_rate_plan_charges.count

      assert_difference "Billing::PlanSubscription::ZuoraRatePlanCharge.count", -1 do
        Billing::PlanSubscription::ZuoraRatePlanCharge.reconcile(
          plan_subscription: plan_subscription,
          active_charges_from_zuora: [charge]
        )
      end
    end
  end

  context "validations" do
    test "validates presence of payload" do
      charge = build :plan_subscription_zuora_rate_plan_charge
      charge.payload = nil
      refute charge.valid?

      assert_includes charge.errors.full_messages, "Payload can't be blank"
    end
  end

  context "delegations" do
    test "delegates missing methods to the underlying zuora rate plan charge's payload" do
      charge = build :plan_subscription_zuora_rate_plan_charge

      object_from_payload = charge.object_from_payload

      assert_equal object_from_payload.name, charge.name
      assert_equal object_from_payload.quantity, charge.quantity
    end

    test "does not delegate methods generated by ActiveRecord" do
      charge = build :plan_subscription_zuora_rate_plan_charge

      object_from_payload = charge.object_from_payload

      refute_equal object_from_payload.id, charge.id
    end
  end
end
