# typed: strict
# frozen_string_literal: true

class Billing::Zuora::Order
  ORDERS_API_VERSION = T.let({ "zuora-version" => "2024-05-20" }.freeze, T::Hash[String, String])

  class CreateParams < T::Struct
    class Subscription < T::Struct
      prop :custom_fields, T.nilable(T::Hash[String, String]), name: "customFields"
      prop :order_actions, T::Array[Billing::Zuora::OrderAction], name: "orderActions"
      prop :subscription_number, T.nilable(String), name: "subscriptionNumber"
    end

    class ProcessingOptions < T::Struct
      # TODO: this will go away with Invoice Settlement
      prop :apply_credit_balance, T.nilable(T::Boolean), name: "applyCreditBalance"
      # Collects payment for invoices generated by the order. Must have run_billing set to true
      prop :collect_payment, T.nilable(T::Boolean), name: "collectPayment"
      prop :refund, T.nilable(T::Boolean)
      prop :refund_amount, T.nilable(Billing::Types::Numeric), name: "refundAmount"
      # Whether create invoices or not against all subscriptions in the order
      prop :run_billing, T.nilable(T::Boolean), name: "runBilling"
    end

    prop :order_date, String, name: "orderDate"
    prop :existing_account_number, T.nilable(String), name: "existingAccountNumber"
    prop :subscriptions, T::Array[Subscription], name: "subscriptions", default: []
    prop :processing_options, T.nilable(ProcessingOptions), name: "processingOptions"
  end

  class CreateResponse < T::Struct
    class Subscription < T::Struct
      prop :subscription_number, T.nilable(String), name: "subscriptionNumber"
      prop :subscription_owner_id, T.nilable(String), name: "subscriptionOwnerId"
      prop :subscription_owner_number, T.nilable(String), name: "subscriptionOwnerNumber"
      prop :subscription_id, T.nilable(String), name: "subscriptionId"
      prop :status, T.nilable(String)
    end

    class Reason < T::Struct
      prop :code, String
      prop :message, String
    end

    prop :process_id, T.nilable(String), name: "processId"
    prop :reasons, T::Array[Billing::Zuora::Order::CreateResponse::Reason], default: []
    prop :request_id, T.nilable(String), name: "requestId"

    prop :success, T::Boolean
    prop :order_number, T.nilable(String), name: "orderNumber"
    prop :status, T.nilable(String)
    prop :order_id, T.nilable(String), name: "orderId"
    prop :account_id, T.nilable(String), name: "accountId"
    prop :account_number, T.nilable(String), name: "accountNumber"
    prop :subscriptions, T::Array[Billing::Zuora::Order::CreateResponse::Subscription], default: []
  end

  sig { params(params: CreateParams).returns(CreateResponse) }
  def self.create(params)
    response = GitHub.zuorest_client.create_order(params.serialize, return_ids: true, headers: ORDERS_API_VERSION)
    CreateResponse.from_hash(response)
  end
end
