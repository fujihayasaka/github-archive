# typed: true
# frozen_string_literal: true

require "test_helper"

class PullRequests::Copilot::CodeReviewCreatorTest < GitHub::TestCase
  fixtures do
    @owner = create(:paid_user)
    @org = create(:organization, admin: @owner)
    @repo  = create(:private_repository, owner: @org, from_example: :with_tokens)

    base_ref = @repo.heads.find("master")
    head_ref = @repo.heads.create("topic", base_ref.target, @repo.owner)
    head_ref.append_commit({
      message: "a change",
      committer: @repo.owner,
    }, @repo.owner) do |files|
      content = "// PullRequestReview represents a review that contains comments from Copilot.\n// Second line"
      files.add("file1", content)
    end

    @pull = PullRequest.create_for! @repo, user: @owner, base: "master", head: "topic", title: "asdf", body: "asdf"

    make_trusted_oauth_apps_owner
    integration = Apps::Privileged::CopilotPullRequestReviewer.seed_database!
    PrivilegedAppHelper.reconfigure_privileged_app(app_alias: :copilot_pull_request_reviewer, app: integration)
    @bot = ::Apps::Privileged.integration(:copilot_pull_request_reviewer).bot
  end

  setup do
    PullRequests::Copilot::CodeReviewAccess.any_instance.stubs(:can_create_review_request?).returns(true)
  end

  test "should return review with comments", skip_enterprise: true do
    Failbot.expects(:report).never
    @pull.stubs(:changed_files).returns(1)

    comment = {
      path: "file1",
      line: 1,
      body: "This is a suggestion",
      side: "RIGHT",
    }
    @pull.review_requests.create(reviewer: @bot)
    creator = PullRequests::Copilot::CodeReviewCreator.new(
      pull: @pull,
      repo: @repo,
      commit_id: @pull.head_sha,
      comments: [comment],
      diff_start_commit_oid: @pull.base_sha,
      diff_end_commit_oid: @pull.head_sha,
      diff_base_commit_oid: @pull.merge_base,
      body: "suggestion",
      return_with_error: false,
    )
    creator.create
    @pull.reload
    @pull.reviews.first.tap do |review|
      assert_equal "suggestion", review.body
      assert_equal review.review_comments.first.body, "This is a suggestion"
    end
  end

  test "Should return error if return_with_error is passed", skip_enterprise: true do
    @pull.review_requests.create(reviewer: @bot)

    PullRequests::Copilot::CodeReviewCreator.new(
      pull: @pull,
      repo: @repo,
      commit_id: @pull.head_sha,
      comments: [],
      diff_start_commit_oid: @pull.base_sha,
      diff_end_commit_oid: @pull.head_sha,
      diff_base_commit_oid: @pull.merge_base,
      body: "error body",
      return_with_error: true,
    ).create

    @pull.reload
    assert_equal "Copilot encountered an error and was unable to review this pull request. You can try again by re-requesting a review.", @pull.reviews.first.body
  end

  test "creates review with no suggestions comment if there are no comments generated by copilot", skip_enterprise: true do
    @pull.review_requests.create(reviewer: @bot)
    PullRequests::Copilot::CodeReviewCreator.new(
      pull: @pull,
      repo: @repo,
      commit_id: @pull.head_sha,
      comments: [],
      diff_start_commit_oid: @pull.base_sha,
      diff_end_commit_oid: @pull.head_sha,
      diff_base_commit_oid: @pull.merge_base,
      body: "empty body",
      return_with_error: false,
    ).create

    @pull.reload
    assert_equal "empty body", @pull.reviews.first.body
  end

  test "creates PullRequests::Copilot::CodeReviewComment record for comments generated from custom coding guideline", skip_enterprise: true do
    Failbot.expects(:report).never
    @pull.stubs(:changed_files).returns(1)

    comment_with_guideline = {
      path: "file1",
      line: 1,
      body: "plz follow the guideline",
      side: "RIGHT",
      problem_type: PullRequests::Copilot::CodeReviewCreator::CODING_GUIDELINE_PROBLEM_TYPE,
      guideline_id: 1,
    }

    comment_without_guideline = {
      path: "file1",
      line: 2,
      body: "no guideline here",
      side: "RIGHT",
    }

    @pull.review_requests.create(reviewer: @bot)
    assert_empty @pull.reviews

    creator = PullRequests::Copilot::CodeReviewCreator.new(
      pull: @pull,
      repo: @repo,
      commit_id: @pull.head_sha,
      comments: [comment_with_guideline, comment_without_guideline],
      diff_start_commit_oid: @pull.base_sha,
      diff_end_commit_oid: @pull.head_sha,
      diff_base_commit_oid: @pull.merge_base,
      body: "LGTM",
      return_with_error: false,
    )

    differences = {
      "PullRequestReview.count" => 1,
      "PullRequestReviewThread.count" => 2,
      "PullRequestReviewComment.count" => 2,
      "PullRequests::Copilot::CodeReviewComment.count" => 1,
    }

    assert_difference(differences) do
      creator.create
    end
  end

  test "destroy any existing review if process fails", skip_enterprise: true do
    Failbot.expects(:report).never

    # Create review request
    @pull.review_requests.create(reviewer: @bot)

    comment = {
      path: "pkg/codereviewagent/pullrequestreview.go",
      line: 17,
      body: "The word 'reprsents' should be corrected to 'represents'.\n```suggestion\n    // PullRequestReview represents a review that contains comments from Copilot.\n```",
      side: "RIGHT",
    }

    assert_empty @pull.reviews

    # results in an error because comment is an invalid type
    refute PullRequests::Copilot::CodeReviewCreator.new(
      pull: @pull,
      repo: @repo,
      commit_id: @pull.head_sha,
      comments: [comment],
      diff_start_commit_oid: @pull.base_sha,
      diff_end_commit_oid: @pull.head_sha,
      diff_base_commit_oid: @pull.merge_base,
      body: nil,
      return_with_error: false,
    ).create

    assert_empty @pull.reviews.reload
  end

  test "destroy the review when no commments were generated", skip_enterprise: true do
    Failbot.expects(:report).never

    # Create review request
    @pull.review_requests.create(reviewer: @bot)

    comment1 = {
      path: "pkg/codereviewagent/pullrequestreview.go",
      line: 17,
      body: "The word 'reprsents' should be corrected to 'represents'.\n```suggestion\n    // PullRequestReview represents a review that contains comments from Copilot.\n```",
      side: "RIGHT",
    }

    comment2 = {
      path: "pkg/codereviewagent/pullrequestreview.go",
      line: 25,
      body: "another comment from copilot",
      side: "RIGHT",
    }

    assert_empty @pull.reviews

    # results in an error because comment is an invalid type
    refute PullRequests::Copilot::CodeReviewCreator.new(
      pull: @pull,
      repo: @repo,
      commit_id: @pull.head_sha,
      comments: [comment1, comment2],
      diff_start_commit_oid: @pull.base_sha,
      diff_end_commit_oid: @pull.head_sha,
      diff_base_commit_oid: @pull.merge_base,
      body: nil,
      return_with_error: false,
    ).create

    assert_empty @pull.reviews.reload
  end

  test "review still posted even if some comments could not be generated", skip_enterprise: true do
    Failbot.expects(:report).never

    # Create review request
    @pull.review_requests.create(reviewer: @bot)

    valid_comment = {
      path: "file1",
      line: 1,
      body: "The word 'reprsents' should be corrected to 'represents'.\n```suggestion\n    // PullRequestReview represents a review that contains comments from Copilot.\n```",
      side: "RIGHT",
      type: "spelling",
    }

    invalid_comment = {
      path: "pkg/codereviewagent/pullrequestreview.go",
      line: 25,
      body: "another comment from copilot",
      side: "RIGHT",
    }

    assert_empty @pull.reviews

    assert PullRequests::Copilot::CodeReviewCreator.new(
      pull: @pull,
      repo: @repo,
      commit_id: @pull.head_sha,
      comments: [valid_comment, invalid_comment],
      diff_start_commit_oid: @pull.base_sha,
      diff_end_commit_oid: @pull.head_sha,
      diff_base_commit_oid: @pull.merge_base,
      body: nil,
      return_with_error: false,
    ).create

    @pull.reviews.reload
    assert_equal 1, @pull.reviews.length
    assert_equal 1, @pull.reviews.first.review_comments.length
  end
end
