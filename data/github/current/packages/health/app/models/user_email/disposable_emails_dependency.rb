  # Internal: Ensure users can't verify new disposable emails
  # Already-verified diposable emails should not invalidate the record
  def cannot_verify_disposable_emails
    # This code runs as a validate callback on UserEmail update event
    # Basically, when the state changes to "verified" for a disposable email that means:
    # Someone tries to mark disposable email as verified, and we should throw an error
    # It's just a safety check and users should not be able to do this
    if state == "verified" && disposable?
      errors.add(:email, "has a domain that cannot be verified")
    end
  end

  # Internal: Instrument the email verification request.
  #
  # Returns nothing.
  def instrument_disposable_email_created
    GitHub.dogstats.increment "user_email.disposable.created", tags: ["domain:#{domain}"]
  end
