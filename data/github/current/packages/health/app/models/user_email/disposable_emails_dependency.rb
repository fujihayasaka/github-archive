  # Is the email hosted with a disposable email service?
  def disposable?
    return false unless GitHub.prevent_disposable_email_verification?
    DISPOSABLE_EMAIL_DOMAINS.include?(domain)
  end

  def self.disposable_email?(email)
    return false if email.blank?
    return false unless GitHub.prevent_disposable_email_verification?

    downcased_domain = email.split("@").last.to_s.strip.downcase
    return false if downcased_domain.blank?

    DISPOSABLE_EMAIL_DOMAINS.include?(downcased_domain)
  end

