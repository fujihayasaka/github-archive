# typed: strict
# frozen_string_literal: true

module SecurityOverviewAnalytics
  class Initialization
    class BatchedResetJob < BatchedJob
      extend T::Sig
      include GitHub::Memoizer

      queue_as :security_overview_analytics_initialization_batched_reset

      retry_on_dirty_exit
      retry_on_recoverable_exceptions

      use_replicas ApplicationRecord::SecurityOverviewAnalytics,
        ApplicationRecord::Repositories,
        ApplicationRecord::Mysql1,
        ApplicationRecord::Mysql5,
        ApplicationRecord::Configurations

      # Hash lock that based only user inputs (ignores the ones generated by BatchedJob).
      # Manually resetting the lock in finalize_batch is required.
      locked_by timeout: 15.minutes, key: ->(job) do
        organization_ids = job.arguments.dig(0, :organization_ids)
        business_ids = job.arguments.dig(0, :business_ids)
        type = job.arguments.dig(0, :type)

        if organization_ids.blank? && business_ids.blank? && type.blank?
          DEFAULT_LOCK_KEY
        else
          DEFAULT_LOCK_STRINGIFY_PROC.call([organization_ids, business_ids, type])
        end
      end

      around_enqueue do |_, block|
        block.call
      end

      around_perform do |_, block|
        block.call
      end

      sig do
        override.params(
          args: T.untyped,
          offset_item_id: Integer,
          kwargs: T.untyped,
        )
        .returns(T::Array[::Organization])
      end
      def next_batch(*args, offset_item_id:, **kwargs)
        rel = ::Organization.where("#{::Organization.table_name}.id > ?", offset_item_id).order(:id).limit(target_batch_size)

        exclude_private_beta_biz = private_beta_business_ids.present? && !include_private_beta?
        if business_ids.present? || exclude_private_beta_biz
          rel = rel.includes(:business)
          # Exclude private beta businesses unless explicitly requested.
          rel = rel.where.not(businesses: { id: private_beta_business_ids }).or(rel.where(businesses: { id: nil })) if exclude_private_beta_biz
          # Include specific businesses if requested.
          rel = rel.where(businesses: { id: business_ids }) if business_ids.present?
        end

        # Exclude private beta orgs unless explicitly requested.
        rel = rel.where.not(id: private_beta_org_ids) if private_beta_org_ids.present? && !include_private_beta?
        # Include specific orgs if requested.
        rel = rel.where(id: organization_ids) if organization_ids.present?

        rel.to_a
      end

      sig do
        override.params(
          organizations: T::Array[::Organization],
          args: T.untyped,
          offset_item_id: Integer,
          kwargs: T.untyped,
        ).void
      end
      def process_batch(organizations, *args, offset_item_id:, **kwargs)
        return if organizations.empty?

        ids_to_onboard = T.let([], T::Array[Integer])
        organizations.each do |org|
          unless TenantValidationHelper.is_owner_in_scope?(org)
            GitHub.logger.info(
              "Skips org initialization.",
              "code.namespace": self.class.name,
              "code.function": __method__,
              "gh.org.id": org.id,
              "gh.security_overview_analytics.job.reason": "Tenant not in scope."
            )
            GitHub.dogstats.increment(
              "security_overview_analytics.batched_reset_job.org_skipped",
              tags: self.all_stats_tags + ["reason:tenant_not_in_scope"]
            )
            next
          end

          initialization = Initialization.for(org)
          if initialization_only? && (
            type.present? && initialization.initialized?(type: Initialization::Type.deserialize(type)) ||
            initialization.all_initialized?
          )
            GitHub.logger.info(
              "Skips org initialization.",
              "code.namespace": self.class.name,
              "code.function": __method__,
              "gh.org.id": org.id,
              "gh.security_overview_analytics.job.reason": "Tenant already initialized."
            )
            GitHub.dogstats.increment(
              "security_overview_analytics.batched_reset_job.org_skipped",
              tags: self.all_stats_tags + ["reason:tenant_initialized"]
            )
            next
          end

          ids_to_onboard << T.must(org.id)
        end
        ResetJob.perform_later(organization_ids: ids_to_onboard, type:, initialization_only: initialization_only?) if ids_to_onboard.present?

        GitHub.logger.info(
          "Organization reset initiated.",
          "code.namespace": self.class.name,
          "code.function": __method__,
          "gh.security_overview_analytics.batch_size": organizations.size,
          "gh.security_overview_analytics.items_processed": ids_to_onboard,
        )
      end

      sig { params(organizations: T::Array[::Organization], args: T::Array[T.untyped], options: T.untyped).void }
      def finalize_batch(organizations, *args, **options)
        clear_lock
      end

      protected

      sig { override.returns(T::Hash[Symbol, T.untyped]) }
      def logging_context
        super.merge({
          "gh.security_overview_analytics.job.business_ids": business_ids.present? ? "#{business_ids&.first}..#{business_ids&.last}" : [],
          "gh.security_overview_analytics.job.organization_ids": organization_ids.present? ? "#{organization_ids&.first}..#{organization_ids&.last}" : [],
          "gh.security_overview_analytics.job.type": type,
          "gh.security_overview_analytics.job.include_private_beta": include_private_beta?,
          "gh.security_overview_analytics.job.initialization_only": initialization_only?,
          "gh.security_overview_analytics.job.initial_start": arguments.dig(0, :initial_start),
          "gh.security_overview_analytics.job.offset_item_id": arguments.dig(0, :offset_item_id),
          "gh.security_overview_analytics.job.progress": arguments.dig(0, :progress),
        })
      end

      sig { override.returns(T::Hash[Symbol, T.untyped]) }
      def failbot_context
        super.merge({
          app: "github-security-center"
        })
      end

      private

      sig { returns(T.nilable(T::Array[Integer])) }
      memoize def organization_ids
        arguments.dig(0, :organization_ids)
      end

      sig { returns(T.nilable(T::Array[Integer])) }
      memoize def business_ids
        arguments.dig(0, :business_ids)
      end

      sig { returns(T.nilable(String)) }
      memoize def type
        arguments.dig(0, :type)
      end

      sig { returns(T::Boolean) }
      memoize def include_private_beta?
        !!arguments.dig(0, :include_private_beta)
      end

      sig { returns(T::Boolean) }
      memoize def initialization_only?
        !!arguments.dig(0, :initialization_only)
      end

      sig { returns(T::Array[Integer]) }
      memoize def private_beta_business_ids
        GitHub
          .flipper[:security_center_private_beta]
          .actors_value
          .to_a
          .select { |v| v.include?("Business") }
          .map { |v| Integer(v.split(":")[1]) }
      end

      sig { returns(T::Array[Integer]) }
      memoize def private_beta_org_ids
        GitHub
          .flipper[:security_center_private_beta]
          .actors_value
          .to_a
          .select { |v| v.include?("Organization") }
          .map { |v| Integer(v.split(":")[1]) }
      end

      sig { returns(Integer) }
      def target_batch_size
        factor_flag = "security_overview_analytics_batched_reset_job_batch_size_factor".to_sym
        # percentage_of_actors_value ranges from 0.01 to 100
        factor = GitHub.flipper[factor_flag].percentage_of_actors_value
        factor = 1 if factor == 0
        (BATCH_SIZE * factor).floor
      end
    end
  end
end
