    Flipper::Config::ALLOW_OVER_ACTOR_LIMIT.each do |feature_name|
      TEMPORARY_EXCLUSION_LIST[feature_name] = true
    end

    def enabled?(thing = nil)
      T.bind(self, T.untyped)
      if name != :flipper_vexi_proxy_redirect && GitHub.use_flipper_vexi_proxy_redirect
        # name can be either a string or a symbol. Convert it to a string for consistancy
        converted_name = name.to_s
        # Check if the feature flag name is included in any of these exclusion lists
        if TEMPORARY_EXCLUSION_LIST[converted_name] || converted_name.match?(EXCLUSION_KEYWORDS_REGEX)
          return super
        end

        use_vexi = GitHub.flipper[:flipper_vexi_proxy_redirect].enabled?(FeatureManagement::FeatureFlagAsFlipperActor.new(converted_name))
        if use_vexi
          begin
            if thing
              return ::FeatureFlag.vexi.enabled?(name, thing)
            end
            return FeatureFlag.vexi.enabled?(name)
          rescue StandardError => ex # rubocop:disable Lint/GenericRescue
            Failbot.report(
              ex,
              feature_name: name.to_s
            )
            GitHub.dogstats.increment("gh.feature_management.flipper_vexi_proxy_redirect.error.count", tags: ["feature_name:#{name}"])
            if GitHub::AppEnvironment.development?
              raise ex
            end
          end
        end
      end
      super
    end
