    # This checks for keys generated by Infineon chips that are vulnerable to
    # CVE-2017-15361.
    #
    # https://www.yubico.com/support/security-advisories/ysa-2017-01/
    #
    # key - An OpenSSL::PKey::RSA instance.
    #
    # Returns boolean.
    def infineon?(key)
      n = key.params["n"]
      INFIEON_FINGERPRINT_ALLOWLIST.none? do |prime, fingerprint|
        !fingerprint.bit_set?(n % prime)
      end
    end
