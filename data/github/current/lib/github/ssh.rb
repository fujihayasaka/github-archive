require "prime"

module GitHub
  module SSH
    extend self

    # To help with coordinated disclosure of incidents, you can mark a blocklist file as requiring a feature flag
    # Add an entry to this map where the key is the filename of the blocklist within config/ssh_key_blocklists, and the value is a feature flag symbol
    # If that feature flag is not enabled, the block list will be ignored.
    FEATURE_FLAGS = {
      # Example:
      # "blocklist.some-security-incident": :blocklist_some_security_incident
    }

    ALL_BLOCKLISTS = Dir[Rails.root.join("config/ssh_key_blocklists/blocklist.*")].to_a.freeze

    def active_blocklists
      ALL_BLOCKLISTS.filter do |path|
        name = File.basename(path)
        flag = FEATURE_FLAGS[name.to_sym]

        # If there's no flag for this block list, enable it.
        next true if flag.nil?

        # Otherwise, enable it if the flag is active.
        GitHub.flipper[flag].enabled?(GitHub::FlipperRole.local_role)
      end
    end

    # Check if the specified key is known to have been compromised.
    #
    # key - a SSHData::PublicKey::Base instance
    #
    # Returns boolean.
    def blocklisted_key?(key)
      result = Progeny::Command.new("grep #{Shellwords.shellescape(key.fingerprint)} #{active_blocklists.join(" ")}")

      if result.status.exitstatus > 1
        Kernel.raise "error checking for compromised key"
      end

      blocked = !result.out.empty?
      if blocked
        # Count attempted uses of blocked keys, to help us decide whether to
        # remove key blocklists
        GitHub.dogstats.increment("ssh.key.blocked")
      end

      blocked
    end

    # Check for security problems with an RSA key.
    #
    # key - An OpenSSL::PKey::RSA instance.
    #
    # Returns boolean.
    def weak_rsa_key?(key)
      small_prime_factor?(key) || infineon?(key)
    end

    # First 10000 primes.
    #
    # Returns an Array of OpenSSL::BN.
    def small_primes
      @small_primes ||= T.must(Prime.first(10000)).map(&:to_bn).freeze
    end

    # Verify that this key's modulus is not trivially factorable.
    #
    # key - An OpenSSL::PKey::RSA instance.
    #
    # Returns boolean.
    def small_prime_factor?(key)
      n = key.params["n"]
      small_primes.any? { |prime| (n % prime).zero? }
    end

