# typed: true
# frozen_string_literal: true

module SAML
  module Shared
    # Shared behavior for SAML requests. Initializes `ID` with a uuid, the
    # `IssueInstant` to the current time, and the `Version` to "2.0".
    #
    # http://www.datypic.com/sc/saml2/t-samlp_RequestAbstractType.html
    module Request
      extend ActiveSupport::Concern

      # Attributes marked with `*` are optional
      #
      attr_accessor :id             # String ID identitifer for this response. Generated by default.
      attr_accessor :version        # String
      attr_accessor :issue_instant  # UTC time of when this response was generated
      attr_accessor :destination    # *String URI describing where this message is destined
      attr_accessor :consent        # *String URI

      def initialize(options = {})
        super
        self.id ||= ("_" + SecureRandom.hex(32))
        self.issue_instant ||= Time.now
        self.version ||= "2.0"
      end
    end
  end
end
