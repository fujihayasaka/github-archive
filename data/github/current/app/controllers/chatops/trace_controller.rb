# typed: true
# frozen_string_literal: true

require "chatops-controller"
require "json"

require "uri"

module Chatops
  class TraceController < ApplicationController
    include ::Chatops::Controller

    depends_on_clusters ApplicationRecord::Mysql1, only: [:list]

    # CAP and verify_authenticity_token not required on chatops controllers
    # since these chatops are run by Hubbers from Slack and the routes for triggering them are only accessible through our internal network
    skip_before_action :perform_conditional_access_checks # rubocop:disable GitHub/DoNotSkipCapBeforeAction
    skip_before_action :verify_authenticity_token

    chatops_namespace :trace
    chatops_help "Commands for working with Datadog APM Traces."

    chatop :mermaid,
        /mermaid\s+(?<traceId>\S+)/,
        "mermaid <traceId> [--flowchart] [--scope <default|service_entries>] - Get markdown formatting the trace given in <traceId> as a mermaid diagram. Diagram will render as gantt if --flowchart not passed in. Default scope for flowchart shows a single node/edge for a service. --scope=service_entries will show first span generated by a service each time it is called. Fetching Traces data depends on unstable Datadog API." do

      trace_id = jsonrpc_params.require(:traceId)

      if trace_id.nil?
        chatop_send("Please specify a trace ID as an argument: `mermaid <traceId>`.")
        return
      end

      options = {
        diagram_type: jsonrpc_params.has_key?(:flowchart) ? "flowchart" : "gantt",
        scope: jsonrpc_params[:scope] || "default",
      }

      markdown = TraceRenderer::MermaidTrace.render(trace_id, **options)

      if markdown.present?
        chatop_send(markdown)
      else
        chatop_send("Error creating mermaid markdown for trace ID: #{trace_id}")
      end
    end
  end
end
