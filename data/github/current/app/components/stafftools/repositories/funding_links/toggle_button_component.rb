# typed: strict
# frozen_string_literal: true

module Stafftools
  module Repositories
    module FundingLinks
      class ToggleButtonComponent < ApplicationComponent
        extend T::Sig

        sig { params(repository: ::Repository).void }
        def initialize(repository:)
          @repository = repository
        end

        private

        sig { returns(::Repository) }
        attr_reader :repository

        sig { returns(T::Boolean) }
        memoize def links_enabled?
          !repository.funding_links_stafftools_disabled?
        end

        sig { returns(T::Boolean) }
        memoize def has_funding_file?
          repository.has_funding_file?
        end

        sig { returns(String) }
        def description
          if has_funding_file?
            "Toggle visibility of this repository's Sponsor button generated by the funding file."
          else
            "This repository does not have a funding file, so you can't toggle the visibility of the Sponsor button."
          end
        end

        sig { returns(String) }
        def button_text
          links_enabled? ? "Disable" : "Enable"
        end

        sig { returns(Symbol) }
        def form_method
          links_enabled? ? :delete : :post
        end
      end
    end
  end
end
