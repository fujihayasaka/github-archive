# typed: strict
# frozen_string_literal: true

# Displays a summary of credentials authorized or owned by a user,
# with links to the relevant stafftools pages for each credential type.
module Stafftools
  module Users
    class CredentialsOverviewComponent < ApplicationComponent
      sig { returns(::User) }
      attr_reader :user

      sig { params(user: ::User).void }
      def initialize(user:)
        @user = T.let(user, ::User)
      end

      sig { returns(T::Array[T::Hash[Symbol, T.untyped]]) }
      def rows
        [
          {
            title: "Fine-grained personal access tokens",
            description: "Fine-grained personal access tokens generated by this account.",
            count: fine_grained_personal_access_tokens_count,
            unit: "token",
            href: stafftools_user_personal_access_tokens_path(user),
            test_selector: "fine-grained-personal-access-tokens",
          },
          {
            title: "Personal access tokens (classic)",
            description: "Personal access tokens (classic) generated by this account.",
            count: classic_personal_access_tokens_count,
            unit: "token",
            href: stafftools_user_oauth_tokens_path(user),
            test_selector: "personal-access-tokens-classic",
          },
          {
            title: "Authorized OAuth apps",
            description: "OAuth apps that have been authorized to access this account.",
            count: authorized_oauth_apps_count,
            unit: "OAuth app",
            href: stafftools_user_applications_path(user),
            test_selector: "authorized-oauth-apps",
          },
          {
            title: "Authorized GitHub Apps",
            description: "GitHub Apps that have been authorized to access this account.",
            count: authorized_github_apps_count,
            unit: "GitHub App",
            href: authorizations_stafftools_user_apps_path(user),
            test_selector: "authorized-github-apps",
          },
          {
            title: "SSH keys",
            description: "SSH keys associated with this account.",
            count: ssh_keys_count,
            unit: "key",
            href: stafftools_user_ssh_keys_path(user),
            test_selector: "ssh-keys",
          },
        ]
      end

      sig { returns(Integer) }
      memoize def fine_grained_personal_access_tokens_count
        ProgrammaticAccess.for(user).count
      end

      sig { returns(Integer) }
      memoize def classic_personal_access_tokens_count
        OauthAccessTokens.domain.personal_tokens_count(user.id)
      end

      sig { returns(Integer) }
      memoize def authorized_oauth_apps_count
        user.oauth_authorizations.oauth_apps.user_revocable(OauthApplication).count
      end

      sig { returns(Integer) }
      memoize def authorized_github_apps_count
        user.oauth_authorizations.github_apps.count
      end

      sig { returns(Integer) }
      memoize def ssh_keys_count
        user.public_keys.count
      end
    end
  end
end
