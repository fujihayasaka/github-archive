# typed: strict
# frozen_string_literal: true

# Renders an overview of the credentials generated or authorized by the given
# user's personal account, broken down into the categories that an enterprise
# owner could revoke via the single-user credential revocation flow:
#
#   * Fine-grained personal access tokens
#   * Personal access tokens (classic)
#   * Authorized OAuth apps
#   * Authorized GitHub Apps
#   * SSH keys
#
# Each category is rendered as a row with a count and a link to the existing
# settings page where the user can manage credentials of that type.
module Settings
  class CredentialsOverviewComponent < ApplicationComponent
    sig { returns(User) }
    attr_reader :user

    sig { params(user: User).void }
    def initialize(user:)
      @user = T.let(user, User)
    end

    sig { returns(T::Array[T::Hash[Symbol, T.untyped]]) }
    def rows
      [
        {
          title: "Fine-grained personal access tokens",
          description: "Fine-grained personal access tokens generated by your personal account.",
          count: fine_grained_personal_access_tokens_count,
          unit: "token",
          href: settings_user_access_tokens_path,
          test_selector: "fine-grained-personal-access-tokens",
        },
        {
          title: "Personal access tokens (classic)",
          description: "Personal access tokens (classic) generated by your personal account.",
          count: classic_personal_access_tokens_count,
          unit: "token",
          href: settings_user_tokens_path,
          test_selector: "personal-access-tokens-classic",
        },
        {
          title: "Authorized OAuth apps",
          description: "OAuth apps that have been authorized to access your account.",
          count: authorized_oauth_apps_count,
          unit: "OAuth app",
          href: settings_user_applications_path,
          test_selector: "authorized-oauth-apps",
        },
        {
          title: "Authorized GitHub Apps",
          description: "GitHub Apps that have been authorized to access your account.",
          count: authorized_github_apps_count,
          unit: "GitHub App",
          href: settings_user_app_authorizations_path,
          test_selector: "authorized-github-apps",
        },
        {
          title: "SSH keys",
          description: "SSH keys associated with your account.",
          count: ssh_keys_count,
          unit: "key",
          href: settings_keys_path,
          test_selector: "ssh-keys",
        },
      ]
    end

    sig { returns(Integer) }
    def fine_grained_personal_access_tokens_count
      ProgrammaticAccess.for(user).count
    end

    sig { returns(Integer) }
    def classic_personal_access_tokens_count
      OauthAccessTokens.domain.personal_tokens_count(user.id)
    end

    sig { returns(Integer) }
    def authorized_oauth_apps_count
      user.oauth_authorizations.oauth_apps.user_revocable(OauthApplication).count
    end

    sig { returns(Integer) }
    def authorized_github_apps_count
      user.oauth_authorizations.github_apps.count
    end

    sig { returns(Integer) }
    def ssh_keys_count
      user.public_keys.count
    end
  end
end
