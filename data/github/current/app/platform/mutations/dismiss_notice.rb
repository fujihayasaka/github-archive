# typed: true
# frozen_string_literal: true

module Platform
  module Mutations
    class DismissNotice < Platform::Mutations::Base
      description "Dismisses a notice for a user."

      minimum_accepted_scopes ["user"]

      visibility :internal

      argument :notice, String, "The type of notice to dismiss.", required: true

      def self.async_api_can_modify?(permission, inputs)
        return false if permission.viewer.nil?

        true
      end

      def resolve(**inputs)
        context[:viewer].dismiss_notice(inputs[:notice])
        # Return an empty hash to satisfy the GraphQL schema (the clientMutationId is auto generated by
        # relay on the client side)
        {}
      end
    end
  end
end
