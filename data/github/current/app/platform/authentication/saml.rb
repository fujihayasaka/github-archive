      # Override of the RubySaml::Authrequest class in order to shim in compatible methods to reduce downstream
      # changes, as well as update the request creation to include a Conditions element to match our existing
      # requests.
      class Authrequest < OneLogin::RubySaml::Authrequest
        def id
          uuid
        end

        def create_xml_document(settings)
          request_doc = super(settings)

          root = request_doc.root
          expiry = (GitHub::Authentication::SAML::AUTHN_REQUEST_TIMEOUT / 60).minutes.from_now
          conditions = root.add_element(
            "saml:Conditions",
            {
              "NotBefore" => (expiry - GitHub::Authentication::SAML::AUTHN_REQUEST_TIMEOUT).utc.strftime("%Y-%m-%dT%H:%M:%SZ"),
              "NotOnOrAfter" => (expiry).utc.strftime("%Y-%m-%dT%H:%M:%SZ"),
            })
          request_doc
        end
      end

      # Override of the RubySaml::Response class in order to downcase the audiences to match our existing responses.
      class Response < OneLogin::RubySaml::Response
        # For backwards compatibility, we need to ensure that the `valid?` method is still available.
        def valid?(**options)
          is_valid?
        end

        def session_index
          sessionindex
        end

        # Downcase response audiences to ensure consistency when validating against what the customer has saved in the
        # service provider (GitHub). RubySaml will compare the audiences in the response to the `sp_entity_id` option.
        # This preserves legacy validation behavior.
        def audiences
          super.map(&:downcase)
        end

        # Downcase destination to ensure consistency when validating against what GitHub has for the ACS URL
        # (the /saml/consume route). This preserves legacy validation behavior.
        def destination
          super&.downcase
        end

        # Downcase NameID SPNameQualifier to ensure consistency when validating against what GitHub has for the
        # `sp_entity_id` (the URL to the business / org). This preserves legacy validation behavior.
        def name_id_spnamequalifier
          super&.downcase
        end

        def validate_issuer
          return true if options[:skip_issuer]
          super
        end

        # Override of the validate_subject_confirmation method to allow for a case-insensitive comparison of the
        # Recipient value in the subject confirmation data. This is necessary because GitHub doesn't treat business or
        # org URL slugs as case sensitive. In the SP-Initiated flow, this wouldn't be a problem since the Recipient
        # value in the response should match what we sent in the Authn request, but in IdP-Initiated flows, the
        # Recipient value is set to whatever the customer configured the ACS URL value to be, which could break casing
        # from what GH has persisted for that slug value.
        #
        # Example:
        #          https://github.com/enterprises/FABRIKAM/saml/consume (valid ACS config in the IdP)
        #        vs
        #          https://github.com/enterprises/fabrikam/saml/consume (URL generated by gh based off of actual slug)
        #
        # Both take the customer to the same place and are therefore valid ACS values right now, but because of the
        # difference in casing, the Recipient check will trip if not normalized.
        #
        # Note: we still run the original implementation of this method to preserve that behavior, but we skip the
        # Recipient check in that method by setting the `skip_recipient_check` option. This allows us to run our case
        # insensitive version of that check here. This should be viewed as purely additive.
        def validate_subject_confirmation
          return unless super # return early if the original implementation returns false

          return true if options[:skip_subject_confirmation]

          subject_confirmation_nodes = xpath_from_signed_assertion("/a:Subject/a:SubjectConfirmation")

          valid_recipient = subject_confirmation_nodes.any? do |subject_confirmation|
            confirmation_data_node = REXML::XPath.first(
              subject_confirmation,
              "a:SubjectConfirmationData",
              { "a" => ASSERTION }
            )

            next false unless confirmation_data_node

            attrs = confirmation_data_node.attributes
            # Check for recipient in a case-insensitive way. This is necessary because GitHub doesn't treat business
            # slugs or org logins as case sensitve. The customer could put whatever they want in the IdP settings and
            # we'd accept it.
            invalid_recipient = attrs.include?("Recipient") && settings && attrs["Recipient"]&.downcase != settings.assertion_consumer_service_url
            next false if invalid_recipient

            true
          end

          if !valid_recipient
            error_msg = "A valid Recipient was not found on this SubjectConfirmation"
            return append_error(error_msg)
          end

          true
        end

        def validate_name_id
          result = super

          GitHub.logger.info(
            "info.message" => "SAML name_id_spnamequalifier debug",
            "gh.saml.name_id_match" => result,
            "gh.saml.errors" => @errors,
            "gh.saml.sp_entity_id" => settings.sp_entity_id,
            "gh.saml.name_id_spnamequalifier" => name_id_spnamequalifier || "nil",
            "gh.saml.name_id" => name_id&.empty? ? "empty" : name_id || "nil",
          )

          return true if options[:skip_name_id_check]

          result
        end

        # Override of the validate_signature method to bypass the default fingerprint validation (ensuring that
        # the public certificate is the exact same). This is necessary because GitHub currently doesn't validate that
        # the public certificate from the SAML responses matches exactly (fingerprint validation) with the public
        # certificate from the SAML config during initial SAML setup, GitHub only validates that both certificate
        # contains the same public key. It is necessary to bypass the fingerprint validation because there could
        # be cases where a customer setup the initial SAML config but eventually the public certificate registered on
        # GitHub side expired but it was rotated on the IdP side, which resulted in a different certificate coming
        # from the SAML response. GitHub does not enforce expiration on public certificate so there would be a public
        # certificate mismatch in this case, which is why we're only concerning with validating the public key of
        # these certificate.
        #
        # Note: we still run the original implementation of this method to preserve that behavior, but we skip the
        # fingerprint validation in that method by logging the original error that validate_signature provided us and
        # running through these validate_signature checks again without the fingerprint validation. This allows us to
        # run our bypass version of that fingerprint validation here while keeping an eye on the previous failure.
        # This should be viewed as purely additive.
        def validate_signature
          return true if options[:skip_validate_signature]

          old_errors = @errors.clone
          error_msg = "Invalid Signature on SAML Response"
          previous_soft = @soft

          begin
            # `@soft = false` will raise error on failed signature/certificate validations. This will allow us to
            # capture the "Fingerprint mismatch" error, which is the only one we need to make legacy accommodations for.
            @soft = false
            return true if super # super will return true if it was successful
          rescue OneLogin::RubySaml::ValidationError => e
            return append_error(error_msg, true) unless e.message == "Fingerprint mismatch"

            GitHub.logger.info(
              "info.message" => "SAML fingerprint mismatch",
              "gh.sp_entity_id" => settings.sp_entity_id,
            )
          rescue StandardError => e
            GitHub.logger.info(
              "info.message" => "Unexpected error during SAML signature validation",
              "gh.error.message" => e.message,
              "gh.sp_entity_id" => settings.sp_entity_id,
            )

            return append_error(e.message, true)
          ensure
            # Always reset @soft back to the original value, even if we did not rescue the specific error, or super was
            # successful.
            # Even though `validate_signature` is the final validation run, there is no guarantee that it will remain
            # like that in the future, so it's best not to rely on the ordering, and to get things cleaned up properly.
            @soft = previous_soft
          end

          doc = doc_to_validate

          sig_elements = REXML::XPath.match(
            document,
            "/p:Response[@ID=$id]/ds:Signature",
            { "p" => PROTOCOL, "ds" => DSIG },
            { "id" => document.signed_element_id }
          )

          # Check signature node inside assertion
          if sig_elements.nil? || sig_elements.size == 0
            sig_elements = REXML::XPath.match(
              doc,
              "/p:Response/a:Assertion[@ID=$id]/ds:Signature",
              SAML_NAMESPACES.merge({ "ds" => DSIG }),
              { "id" => doc.signed_element_id }
            )
          end

          if sig_elements.size != 1
            if sig_elements.size == 0
              append_error("Signed element id ##{doc.signed_element_id} is not found")
            else
              append_error("Signed element id ##{doc.signed_element_id} is found more than once")
            end
            return append_error(error_msg)
          end

          @errors = old_errors

          idp_cert = settings.get_idp_cert
          if idp_cert
            base64_cert = Base64.encode64(idp_cert.to_pem)
            return append_error(error_msg) unless doc.validate_signature(base64_cert, soft)
          else
            if soft
              return false
            else
              return append_error("No cert provided at settings", soft)
            end
          end

          true
        end

        def validate_one_authnstatement
          # Validate AuthnStatement element only when present in the SAML response.
          # Legacy behavior: Our previous implementation ignored AuthnStatement validation,
          # so we maintain backwards compatibility by skipping validation when absent.
          #
          # The AuthnStatement element serves two purposes:
          # 1. Session expiration time (defaults to 1 day if missing)
          # 2. Session index tracking (used only in GHES)
          #
          # Note: Some IdPs may not include this element. When missing, we use default values
          # to maintain compatibility with existing customer integrations.
          statements = xpath_from_signed_assertion("/a:AuthnStatement")
          return true if options[:skip_authnstatement] || statements.empty?
          GitHub.logger.info(
            "info.message" => "SAML authnstatement validation",
            "gh.saml.authnstatement_count" => statements.length,
            "gh.saml.errors" => @errors
          )
          super
        end

        def request_denied?
          status_code.include?("urn:oasis:names:tc:SAML:2.0:status:RequestDenied")
        end
      end

      class XMLExperimentResult
        attr_reader :invalid_part, :control_value, :candidate_value

        def initialize(control, candidate, namespaces)
          @namespaces = namespaces
          @control = Nokogiri::XML(control)
          @candidate = Nokogiri::XML(candidate)
        rescue Nokogiri::XML::SyntaxError
          @valid = false
          @invalid_part = "XML syntax"
        end

        def success?
          @valid
        end

        def validate(params)
          # check that any of the params is invalid
          params.any? do |param|
            is_valid = run_validation(
              xpath: param[:xpath],
              attribute: param[:attribute],
              presence: param[:presence],
            )
            return true unless is_valid
          end
        end

        private

        def run_validation(xpath:, attribute: nil, presence: false)
          return @valid = false if @control.nil? || @candidate.nil?

          control_node = @control.at_xpath(xpath, @namespaces)
          candidate_node = @candidate.at_xpath(xpath, @namespaces)

          return @valid = false if control_node.nil? || candidate_node.nil?

          if attribute.present?
            @control_value = control_node.get_attribute(attribute)
            @candidate_value = candidate_node.get_attribute(attribute)

            if presence
              @valid = @control_value.present? == @candidate_value.present?
            else
              @valid = @control_value == @candidate_value
            end
          else
            @control_value = control_node.text
            @candidate_value = candidate_node.text
            @valid = @control_value == @candidate_value
          end

          @invalid_part = if attribute.nil?
            xpath
          else
            "#{xpath}[@#{attribute}]"
          end

          @valid
        end
      end

      DEFAULT_EXPIRATION = 5.minutes
      NAME_IDENTIFIER_FORMAT_UNSPECIFIED = "urn:oasis:names:tc:SAML:1.1:nameid-format:unspecified"
      PROTOCOL_BINDING_HTTP_POST = "urn:oasis:names:tc:SAML:2.0:bindings:HTTP-POST"
      XML_NAMESPACES = {
        "md" => "urn:oasis:names:tc:SAML:2.0:metadata",
        "samlp" => "urn:oasis:names:tc:SAML:2.0:protocol",
        "saml" => "urn:oasis:names:tc:SAML:2.0:assertion",
        "ds" => "http://www.w3.org/2000/09/xmldsig#",
        "xenc" => "http://www.w3.org/2001/04/xmlenc#",
      }

      @@default_consume_options = {
        skip_recipient_check: true, # skip the recipient check since we'll handle that ourselves.
        skip_name_id_check: true,   # some customers do not pass a name ID in their response: https://github.com/github/external-identities/issues/5747
      }

      def initialize(
        target: nil,
        assertion_consumer_service_url:,
        service_provider_url:,
        security:,
        sso_url: nil,
        idp_certificate: nil,
        private_key: nil,
        issuer: nil,
        force_authn: nil,
        passive: nil,
        name_identifier_format: NAME_IDENTIFIER_FORMAT_UNSPECIFIED,
        protocol_binding: PROTOCOL_BINDING_HTTP_POST
      )
        options = {
          assertion_consumer_service_url: assertion_consumer_service_url,
          sp_entity_id: service_provider_url,
          security: security
        }

        unless sso_url.nil?
          options[:idp_sso_service_url] = sso_url
        end

        unless idp_certificate.nil?
          begin
            # There is legacy SAML provider data that includes bad data before or after the certificate. This will
            # strip that out so that ruby-saml doesn't trip on the certificate.
            sanitized_idp_certificate = OpenSSL::X509::Certificate.new(idp_certificate).to_pem
            options[:idp_cert] = sanitized_idp_certificate
          rescue OpenSSL::X509::CertificateError => e
            GitHub.logger.info(
              "info.message" => "CertificateError during pem conversion",
              "error.message" => e.message
            )
            options[:idp_cert] = idp_certificate
          end
        end

        unless private_key.nil?
          options[:private_key] = private_key.to_s
        end

        unless issuer.nil? || issuer.empty?
          options[:idp_entity_id] = issuer
        end

        unless force_authn.nil?
          options[:force_authn] = force_authn
        end

        unless passive.nil?
          options[:passive] = passive
        end

        unless name_identifier_format.nil?
          options[:name_identifier_format] = name_identifier_format
        end

        unless protocol_binding.nil?
          options[:protocol_binding] = protocol_binding
        end

        @target = target
        @settings = OneLogin::RubySaml::Settings.new(options)
      end

      def generate_metadata
        pretty_print = false
        valid_until = DEFAULT_EXPIRATION.from_now

        OneLogin::RubySaml::Metadata.new.generate(@settings, pretty_print, valid_until)
      end

      # Public: Generate a SAML metadata document for the given ACS and SP URLs.
      def self.generate_metadata(acs_url, sp_url)
        new(
          assertion_consumer_service_url: acs_url,
          service_provider_url: sp_url,
          security: {
            authn_requests_signed: false,
            want_assertions_signed: false,
          }
        ).generate_metadata
      end

      def generate_authn_request_url(authn_request, relay_state)
        query_params = { RelayState: relay_state }

        authn_request.create(@settings, query_params)
      end

      # Public: Generate a SAML authentication request URL.
      #
      # authn_request - The SAML authentication request object.
      # relay_state - The relay state to be included in the request.
      # sso_url - The Single Sign-On (SSO) URL of the Identity Provider (IdP).
      # service_provider_url - The URL of the Service Provider (SP).
      # assertion_consumer_service_url - The URL where the IdP will send the SAML assertion.
      # signature_method - The method used to sign the request.
      # digest_method - The method used to create the digest of the request.
      # force_authn - Optional. Forces the IdP to re-authenticate the user.
      # name_identifier_format - Optional. The format of the name identifier.
      # protocol_binding - Optional. The protocol binding to be used.
      # passive - Optional. Whether the request is passive.
      #
      # Returns the generated authentication request URL.
      def self.generate_authn_request_url(
        authn_request,
        relay_state,
        sso_url,
        service_provider_url,
        assertion_consumer_service_url,
        signature_method,
        digest_method,
        force_authn = nil,
        name_identifier_format: NAME_IDENTIFIER_FORMAT_UNSPECIFIED,
        protocol_binding: PROTOCOL_BINDING_HTTP_POST,
        passive: false
      )
        new(
          assertion_consumer_service_url: assertion_consumer_service_url,
          service_provider_url: service_provider_url,
          security: {
            signature_method: signature_method,
            digest_method: digest_method,
          },
          sso_url: sso_url,
          force_authn: force_authn || nil,
          passive: passive,
          name_identifier_format: name_identifier_format,
          protocol_binding: protocol_binding,
        ).generate_authn_request_url(authn_request, relay_state)
      end

      private def consume(response)
        saml_response = Response.new(response, {
          settings: @settings,
          **@@default_consume_options,
        })

        validation_errors = tag_saml_responses(saml_response)

        unless validation_errors.nil?
          return Platform::Authentication::SamlResult.invalid(saml_response)
        end

        unless saml_response.is_valid?
          return Platform::Authentication::SamlResult.invalid(saml_response)
        end

        if saml_response.success?
          Platform::Authentication::SamlResult.authorized(saml_response)
        else
          Platform::Authentication::SamlResult.unauthorized(saml_response)
        end
      rescue StandardError => err
        GitHub.logger.error(
          "info.message" => "Error consuming SAML response",
          "error.message" => err.message,
          "saml.errors" => saml_response.nil? ? [] : saml_response.errors,
          "gh.saml.target_type" => @target&.class&.name,
          "gh.saml.target_id" => @target&.id,
          "gh.saml.target_slug" => @target&.to_s,
        )
        Platform::Authentication::SamlResult.invalid(errors: err.message)
      end

      def process_response(response)
        auth_result = consume(response)

        if auth_result.success?
          auth_result.user_data = Platform::Provisioning::SamlUserData.load(
            auth_result.assertion,
            persist_attributes: true,
          )
        end

        auth_result
      end

      def self.process_response(
        target,
        raw_response,
        assertion_consumer_service_url:,
        sp_url:,
        idp_certificate:,
        issuer:,
        digest_method:,
        signature_method:,
        private_key: nil
      )
        new(
          target: target,
          assertion_consumer_service_url: assertion_consumer_service_url.downcase,
          service_provider_url: sp_url.downcase,
          security: {
            digest_method: digest_method,
            signature_method: signature_method,
            strict_audience_validation: true,
          },
          idp_certificate: idp_certificate,
          private_key: private_key,
          issuer: issuer,
        ).process_response(raw_response)
      end

      def self.metadata_match?(control, candidate)
        check_params = [
          { xpath: "//md:EntityDescriptor", attribute: "entityID" },
          { xpath: "//md:EntityDescriptor", attribute: "validUntil", presence: true },
          { xpath: "//md:AssertionConsumerService", attribute: "Location" },
          { xpath: "//md:AssertionConsumerService", attribute: "Binding" },
          { xpath: "//md:AssertionConsumerService", attribute: "isDefault" },
          { xpath: "//md:SPSSODescriptor", attribute: "protocolSupportEnumeration" },
          { xpath: "//md:SPSSODescriptor", attribute: "AuthnRequestsSigned" },
          { xpath: "//md:SPSSODescriptor", attribute: "WantAssertionsSigned" },
          { xpath: "//md:NameIDFormat" },
        ]

        experiment_result = XMLExperimentResult.new(control.to_s, candidate, XML_NAMESPACES)
        experiment_result.validate(check_params)

        GitHub.logger.info(
          "info.message" => "SAML metadata comparison",
          "gh.saml.metadata_match" => experiment_result.success?,
          "gh.saml.metadata_mismatched_part" => experiment_result.invalid_part,
          "gh.saml.metadata_control_value" => experiment_result.control_value,
          "gh.saml.metadata_candidate_value" => experiment_result.candidate_value,
        )

        experiment_result.success?
      end

      def self.initiate_match?(control, candidate)
        check_params = [
          { xpath: "//samlp:AuthnRequest", attribute: "ID", presence: true },
          { xpath: "//samlp:AuthnRequest", attribute: "IssueInstant", presence: true },
          { xpath: "//samlp:AuthnRequest", attribute: "Version" },
          { xpath: "//samlp:AuthnRequest", attribute: "Destination" },
          { xpath: "//samlp:AuthnRequest", attribute: "IsPassive" },
          { xpath: "//samlp:AuthnRequest", attribute: "ProtocolBinding" },
          { xpath: "//samlp:AuthnRequest", attribute: "AssertionConsumerServiceURL" },
          { xpath: "//samlp:AuthnRequest", attribute: "ForceAuthn" },
          { xpath: "//saml:Issuer" },
          { xpath: "//samlp:NameIDPolicy", attribute: "Format" },
          { xpath: "//samlp:NameIDPolicy", attribute: "AllowCreate" },
          { xpath: "//saml:Conditions", attribute: "NotBefore", presence: true },
          { xpath: "//saml:Conditions", attribute: "NotOnOrAfter", presence: true },
        ]

        control_auth_request = control.request.to_s
        candidate_auth_request = parse_saml_auth_request(candidate.strip)

        experiment_result = XMLExperimentResult.new(control_auth_request, candidate_auth_request, XML_NAMESPACES)
        experiment_result.validate(check_params)

        GitHub.logger.info(
          "info.message" => "SAML initiate comparison",
          "gh.saml.initiate_match" => experiment_result.success?,
          "gh.saml.initiate_mismatched_part" => experiment_result.invalid_part,
          "gh.saml.initiate_control_value" => experiment_result.control_value,
          "gh.saml.initiate_candidate_value" => experiment_result.candidate_value,
        )

        experiment_result.success?
      end

      def self.consume_match?(control, candidate, target_type = nil, target = nil)
        log_saml_comparison(control, candidate, target_type, target)

        control.success? == candidate.success? && control.failure_type == candidate.failure_type
      end

      def self.log_saml_comparison(control, candidate, target_type, target)
        control_failure_type = control.failure_type.nil? ? "nil" : control.failure_type
        candidate_failure_type = candidate.failure_type.nil? ? "nil" : candidate.failure_type

        control_errors = if control.assertion.is_a?(Hash)
          control.assertion[:errors]
        elsif control.assertion.respond_to?(:errors)
          control.assertion.errors
        else
          nil
        end

        candidate_errors = if candidate.assertion.is_a?(Hash)
          candidate.assertion[:errors]
        elsif candidate.assertion.respond_to?(:errors)
          candidate.assertion.errors
        else
          nil
        end

        consume_match = control.success? == candidate.success? && control_failure_type == candidate_failure_type

        GitHub.logger.info(
          "info.message" => "SAML consume comparison",
          "gh.request_id" => GitHub.context[:request_id],
          "gh.saml.target_type" => target_type,
          "gh.saml.target_id" => target&.id,
          "gh.saml.target_slug" => target_type == "business" ? target&.slug : target&.display_login,
          "gh.saml.consume_match" => consume_match,
          "gh.saml.consume_control_success" => control.success?,
          "gh.saml.consume_candidate_success" => candidate.success?,
          "gh.saml.consume_control_failure_type" => control_failure_type,
          "gh.saml.consume_candidate_failure_type" => candidate_failure_type,
          "gh.saml.consume_control_errors" => control_errors&.to_json,
          "gh.saml.consume_candidate_errors" => candidate_errors&.to_json
        )
      end

      private_class_method def self.parse_saml_auth_request(url)
        query_params = Addressable::URI.parse(url).query_values
        decoded  = Base64.urlsafe_decode64(query_params["SAMLRequest"])
        zstream  = Zlib::Inflate.new(-Zlib::MAX_WBITS)
        inflated = zstream.inflate(decoded)
      end
    end
