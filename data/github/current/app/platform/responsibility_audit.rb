# typed: true
# frozen_string_literal: true

require "graphql"
require "csv"

module Platform
  # Read a GraphQL schema dump and create a CSV
  # which lists the different things people are responsible for.
  #
  # There's a little bit of customization on top of the schema SDL:
  # since we track responsibility of mutation _classes_, we want to
  # report the responsibility of that _mutation_, not its derived
  # schema members.
  #
  # It's implemented to use the SDL as input instead of the Rails application environment
  # so that it will run a bit faster (doesn't have to load the app).
  #
  #
  # Run it with `$ bin/dump-graphql-responsibilities`
  #
  # @see `script/dump-graphql-responsibilities` for the source code
  class ResponsibilityAudit
    def initialize(schema_path: nil, schema_string: nil)
      schema_ast = if schema_path
        GraphQL.parse_file(schema_path)
      elsif schema_string
        GraphQL.parse(schema_string)
      else
        raise Platform::Errors::Internal, "`schema_path:` or `schema_string:` is required"
      end
      visitor = ResponsibilityVisitor.new(schema_ast)
      visitor.visit
      @responsibilities = visitor.responsibilities
    end

    # @return [String] A file-ready CSV string
    def to_csv
      header = ["Name", "Kind", "Visibility", "Under Development Since"]
      rows = @responsibilities.map do |responsibility|
        [
          responsibility.name,
          responsibility.kind,
          responsibility.visibility,
          responsibility.under_development_since,
        ]
      end

      # Inputs and Payloads may report the same mutation responsibility,
      # so deduplicate now
      rows.uniq!

      CSV.generate do |csv|
        csv << header
        rows.each { |row| csv << row }
      end
    end

    class ResponsibilityVisitor < GraphQL::Language::Visitor
      def initialize(*)
        @responsible_nodes = []
        @mutation_root = nil
        @responsibilities = nil
        super
      end

      # Now that the run is finished, derive responsibilities from the AST nodes.
      # This way, we can correctly manage mutation-derived schema members.
      def responsibilities
        if @mutation_root.nil?
          raise Platform::Errors::Internal, "Invariant: `#responsibilities` can only be called after visiting, and after finding a `@mutation_root`"
        end
        if @responsibilities.nil?
          @responsibilities = []
          @responsible_nodes.each do |ast_node|
            @responsibilities << Responsibility.new(
              schema_member_node: ast_node,
              mutation_root: @mutation_root,
            )
          end
        end
        @responsibilities
      end

      def on_object_type_definition(type_node, schema_node)
        @responsible_nodes << type_node
        if type_node.name == "Mutation"
          @mutation_root = type_node
        end
        super
      end

      def on_interface_type_definition(type_node, schema_node)
        @responsible_nodes << type_node
        super
      end

      def on_union_type_definition(type_node, schema_node)
        @responsible_nodes << type_node
        super
      end

      def on_input_object_type_definition(type_node, schema_node)
        @responsible_nodes << type_node
        super
      end

      def on_enum_type_definition(type_node, schema_node)
        @responsible_nodes << type_node
        super
      end

      def on_scalar_type_definition(type_node, schema_node)
        @responsible_nodes << type_node
        super
      end
    end

    class Responsibility
      attr_reader :name, :kind, :visibility, :under_development_since
      def initialize(schema_member_node:, mutation_root:)
        schema_member_mutation_name = schema_member_node.name.sub(/(Payload|Input)$/, "")
        # This is the default, that the node represents a first class schema member,
        # but it may be overridden below if the node is determined to be
        # derived from a mutation
        @name = schema_member_node.name
        @kind = schema_member_node.class.name.sub(/.*::(.*)TypeDefinition/, "\\1")
        if schema_member_mutation_name != schema_member_node.name
          # Convert the uppercased type name to a lower-first-letter field name
          mutation_field_name = schema_member_mutation_name[0].downcase + schema_member_mutation_name[1..-1]
          if mutation_root.fields.any? { |f| f.name == mutation_field_name }
            # In this case, this AST node was generated by a mutation,
            # so report that mutation instead.
            @name = schema_member_mutation_name
            @kind = "Mutation"
          end
        end

        if schema_member_node.directives.any? { |d| d.name == "internal" }
          @visibility = "internal"
          @under_development_since = nil
        elsif (under_development_node = schema_member_node.directives.find { |d| d.name == "underDevelopment" })
          @visibility = "underDevelopment"
          @under_development_since = under_development_node.arguments.first.value
        else
          @visibility = "public"
          @under_development_since = nil
        end
      end
    end
  end
end
