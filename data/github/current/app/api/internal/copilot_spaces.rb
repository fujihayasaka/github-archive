# typed: true
# frozen_string_literal: true

class Api::Internal::CopilotSpaces < Api::Internal
  def externally_accessible?
    false
  end

  def require_request_hmac?
    false
  end

  get "/internal/copilot/spaces/:owner/:number", operation_id: :internal, read_from_replicas: true do
    control_access :read_user,
      resource: current_user,
      challenge: true,
      allow_integrations: true,
      allow_user_via_granular_actor: true

    return deliver_error 404, message: "Not found" unless copilot_spaces_enabled?

    # Find the copilot space
    owner = User.find_by_login(params[:owner]) || Organization.find_by_login(params[:owner])
    return deliver_error 404, message: "Owner not found" unless owner

    copilot_space = CopilotSpace.find_by(number: params[:number], owner: owner)
    return deliver_error 404, message: "Not found" unless copilot_space

    # Check if user can read this space
    return deliver_error 404, message: "Not found" unless copilot_space.readable_by?(current_user)

    # Set required attributes for payload generation
    copilot_space.current_user = current_user
    copilot_space.cap_filter = cap_filter

    payload = ::CopilotSpaces::PageData::CopilotSpace::Payload.call(copilot_space).as_json
    deliver_raw(payload, status: 200)
  end

  post "/internal/copilot/spaces", operation_id: :internal, read_from_replicas: true do
    control_access :read_user,
      resource: current_user,
      challenge: true,
      allow_integrations: true,
      allow_user_via_granular_actor: true

    return deliver_error 404, message: "Not found" unless copilot_spaces_enabled?

    data = receive_with_openapi

    owner = get_owner(data)
    return deliver_error 404, message: "Owner not found" unless owner

    copilot_space = CopilotSpace.new(filter_copilot_space_params(data))
    copilot_space.owner = owner
    copilot_space.creator = current_user
    copilot_space.current_user = current_user
    copilot_space.cap_filter = cap_filter

    ::CopilotSpaces::HydroEventsHelper.instrument_hydro_events(:create, copilot_space, current_user, cap_filter)

    with_write do
      if CopilotSpace::Persistence.save(copilot_space:, current_user:, cap_filter:, action: :create)
        # Grant admin role to creator
        Permissions::Granters::RoleGranter.new(actor: current_user, target: copilot_space, role: Role.custom_copilot_admin_role).grant!

        # Generate payload similar to the controller
        payload = ::CopilotSpaces::PageData::CopilotSpace::Payload.call(copilot_space).as_json
        deliver_raw(payload, status: 200)
      else
        # Clear autogenerated number that wouldn't exist in database
        copilot_space.number = nil

        error_messages = format_error_messages(copilot_space.errors)
        deliver_raw({ errorMessages: error_messages }, status: 422)
      end
    end
  end

  put "/internal/copilot/spaces/:owner/:number", operation_id: :internal, read_from_replicas: true do
    control_access :read_user,
      resource: current_user,
      challenge: true,
      allow_integrations: true,
      allow_user_via_granular_actor: true

    return deliver_error 404, message: "Not found" unless copilot_spaces_enabled?

    # Find the copilot space
    owner = User.find_by_login(params[:owner]) || Organization.find_by_login(params[:owner])
    return deliver_error 404, message: "Owner not found" unless owner

    copilot_space = CopilotSpace.find_by(number: params[:number], owner: owner)
    return deliver_error 404, message: "Copilot space not found" unless copilot_space

    # Check if user can edit this space
    return deliver_error 404, message: "Not found" unless copilot_space.editable_by?(current_user)

    data = receive_with_openapi
    params_to_update = filter_update_copilot_space_params(data)

    # Handle duplicate github file resources before assigning to the model
    if params_to_update[:resources_attributes].present?
      handle_duplicate_github_file_resources(copilot_space, params_to_update[:resources_attributes])
    end

    copilot_space.assign_attributes(params_to_update)
    copilot_space.current_user = current_user
    copilot_space.cap_filter = cap_filter

    ::CopilotSpaces::HydroEventsHelper.instrument_hydro_events(:update, copilot_space, current_user, cap_filter)

    with_write do
      if CopilotSpace::Persistence.save(copilot_space:, current_user:, cap_filter:, action: :update)
        # Generate payload similar to the controller
        payload = ::CopilotSpaces::PageData::CopilotSpace::Payload.call(copilot_space).as_json
        deliver_raw(payload, status: 200)
      else
        error_messages = format_error_messages(copilot_space.errors)
        deliver_raw({ errorMessages: error_messages }, status: 422)
      end
    end
  end

  private

  def copilot_spaces_enabled?
    current_copilot_user_v2 = Copilot::Public::User.new(current_user)
    (current_user&.feature_flag_enabled_or_raise?(:copilot_custom_copilots) || # rubocop:disable GitHub/FeatureManagement/NoVexiActorFeatureFlagEnabledOrRaiseUsage
      (current_user&.feature_flag_enabled_or_raise?(:copilot_custom_copilots_feature_preview) && # rubocop:disable GitHub/FeatureManagement/NoVexiActorFeatureFlagEnabledOrRaiseUsage
      (current_copilot_user_v2.beta_features_github_chat_enabled? || current_copilot_user_v2.has_limited_access?))
    )
  end

  def get_owner(data)
    return current_user unless data["owner_type"] && data["owner_id"]

    if data["owner_type"] == "Organization"
      org = Organization.find_by(id: data["owner_id"])
      return org if org
      return nil # Return nil for non-existent organization
    end

    current_user
  end

  def filter_copilot_space_params(data)
    # Define allowed parameters similar to controller
    allowed_params = %w[
      name
      description
      general_instructions
      icon_type
      icon_color
      visibility
      base_role
      owner_id
      owner_type
    ]

    filtered = data.slice(*allowed_params)

    # Handle resources if present
    if data["resources_attributes"].present?
      filtered["resources_attributes"] = filter_resources_attributes(data["resources_attributes"])
    end

    # Convert string keys to symbols for ActiveRecord
    filtered.transform_keys(&:to_sym)
  end

  def filter_resources_attributes(resources)
    allowed_resource_params = %w[
      resource_type
      copilot_chat_attachment_id
    ]

    allowed_metadata_params = %w[
      repository_id
      file_path
      text
      name
      number
      media_type
      url
      height
      width
      size
    ]

    resources.map do |resource|
      filtered_resource = resource.slice(*allowed_resource_params)

      # Remove id for new resources
      filtered_resource.delete("id")

      if resource["metadata"].present?
        filtered_resource["metadata"] = resource["metadata"].slice(*allowed_metadata_params)
      end

      # Convert string keys to symbols for ActiveRecord
      filtered_resource.transform_keys(&:to_sym)
    end
  end

  def format_error_messages(errors)
    errors.messages.transform_values do |error_messages|
      # Convert error messages from array to sentence for UI display
      error_messages.to_sentence
    end
  end

  def filter_update_copilot_space_params(data)
    # Define allowed parameters for update (excluding owner_id and owner_type)
    allowed_params = %w[
      name
      description
      general_instructions
      icon_type
      icon_color
      visibility
      base_role
    ]

    filtered = data.slice(*allowed_params)

    # Handle resources if present
    if data["resources_attributes"].present?
      filtered["resources_attributes"] = filter_update_resources_attributes(data["resources_attributes"])
    end

    # Convert string keys to symbols for ActiveRecord
    filtered.transform_keys(&:to_sym)
  end

  def filter_update_resources_attributes(resources)
    allowed_resource_params = %w[
      resource_type
      copilot_chat_attachment_id
      id
      _destroy
    ]

    allowed_metadata_params = %w[
      repository_id
      file_path
      text
      name
      number
      media_type
      url
      height
      width
      size
    ]

    # Filter out disallowed resource types based on feature flags
    disallowed_resource_types = [].tap do |types|
      types << CopilotSpaceResource::Constants::MEDIA_CONTENT unless current_user&.feature_flag_enabled_or_raise?(:copilot_custom_copilots_images) # rubocop:disable GitHub/FeatureManagement/NoVexiActorFeatureFlagEnabledOrRaiseUsage
    end

    filtered_resources = resources.reject do |resource|
      disallowed_resource_types.include?(resource["resource_type"])
    end

    filtered_resources.map do |resource|
      filtered_resource = resource.slice(*allowed_resource_params)

      if resource["metadata"].present?
        filtered_resource["metadata"] = resource["metadata"].slice(*allowed_metadata_params)
      end

      # Convert string keys to symbols for ActiveRecord
      filtered_resource.transform_keys(&:to_sym)
    end
  end

  def handle_duplicate_github_file_resources(copilot_space, resources_attributes)
    return unless resources_attributes.present?

    # Only process new github file resources (those without IDs)
    new_github_file_resources = resources_attributes.select do |resource|
      resource[:id].blank? && resource[:resource_type] == CopilotSpaceResource::Constants::GITHUB_FILE
    end

    return if new_github_file_resources.empty?

    # Find existing github file resources for this custom copilot
    existing_resources = copilot_space.resources
      .where(resource_type: :github_file)
      .select([:id, :metadata])
      .to_a

    # Create a key generator lambda for consistent key generation
    key_generator = ->(repo_id, file_path) { "#{repo_id}:#{file_path}" if repo_id.present? && file_path.present? }

    # Create a lookup hash for quick duplicate checking
    existing_lookup = {}
    existing_resources.each do |resource|
      repo_id = resource.metadata["repository_id"]
      file_path = resource.metadata["file_path"]
      next unless repo_id.present? && file_path.present?

      key = key_generator.call(repo_id, file_path)
      existing_lookup[key] = true
    end

    new_github_file_resources.each do |resource|
      repository_id = resource[:metadata]["repository_id"]
      file_path = resource[:metadata]["file_path"]

      next unless repository_id.present? && file_path.present?

      # Check if this would be a duplicate
      key = key_generator.call(repository_id, file_path)
      resources_attributes.delete(resource) if existing_lookup[key]
    end

    resources_attributes
  end
end
