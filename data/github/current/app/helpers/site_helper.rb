  sig { params(mode: T.any(String, Symbol), dark_theme: T.any(String, Symbol), light_theme: T.any(String, Symbol)).returns(String) }
  def mktg_color_theme_attributes(mode: "dark", dark_theme: "dark", light_theme: "light")
