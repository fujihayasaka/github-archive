module SiteHelper
  extend T::Helpers

  # Adds a 'return_to' param to the login url so that successful
  # login sends you right back to where you were.
  sig { params(options: T::Hash[Symbol, T.untyped]).returns(String) }
  def site_nav_login_path(options = {})
    invalid_return_paths = ["/", "/dashboard/logged_out"]
    request = T.let(T.unsafe(self).request, ActionDispatch::Request) # Global request object, passed from the controller

    unless invalid_return_paths.include?(request.path)
      options[:return_to] = coordinated_return_to
    end

    T.unsafe(self).login_path(options) # Automatically generated by Rails from `login` route
  end

  sig { returns(T.nilable(String)) }
  def coordinated_return_to
    request = T.let(T.unsafe(self).request, ActionDispatch::Request) # Global request object, passed from the controller
    params = T.let(T.unsafe(self).params, T.any(ActionController::Parameters, Hash)) # Global request url params object, passed from the controller

    if request.path == "/join" && params[:setup_organization]
      T.unsafe(self).new_organization_path # Automatically generated from Rails `resources :organizations` in /config/routes.rb
    else
      params[:return_to] || T.unsafe(self).return_to_path # from /app/helpers/url_helper.rb#L884
    end
  end

  sig { returns(T::Boolean) }
  def home_page?
    request = T.let(T.unsafe(self).request, ActionDispatch::Request) # Global request object, passed from the controller

    request.path == T.unsafe(self).home_path || # Automatically generated from Rails `get 'home'` in /config/routes.rb
    request.path == "/home"
  end

  # Note: Only used by logged out header /app/views/site/_marketing_header.html.erb#L284
  sig { returns(T::Boolean) }
  def display_signin_popover?
    response = T.let(T.unsafe(self).response, ActionDispatch::Response) # Global response object, passed from the controller

    return false if !response.not_found?
    return false if GitHub.private_mode_enabled?
    return false if !T.unsafe(self).customized(:sign_in_message).blank? # From /app/helpers/custom_messages_helper.rb#L7

    true
  end

  # Note: Only used by logged in header /app/views/site/header/logged_in/_user.html.erb#L7
  # The switch account popover is a popover that appears when a user
  # receives a not_found response. This could be because they are not
  # authorized to view the page, or because the page does not exists.
  # We cannot distinguish between these two cases, because we don't want to
  # leak existence of a resource, so we show the popover in both cases.
  # We only show the popover if the user is logged in and has valid stashed accounts.
  sig { returns(T::Boolean) }
  def display_switch_account_popover?
    response = T.let(T.unsafe(self).response, T.nilable(ActionDispatch::Response)) # Global response object, passed from the controller

    return false unless response&.not_found?
    return false if @disable_account_switcher_popover
    return false unless T.unsafe(self).logged_in? # From app/controllers/application_controller/authenticated_system.rb#L16
    return false unless T.unsafe(self).account_switcher_helper.enabled? # From /app/controllers/application_controller/saved_user_sessions_cookie_dependency.rb#L25

    elligible = T.unsafe(self).account_switcher_helper.stashed_accounts.valid.any?

    if elligible && T.unsafe(self).flash[:stale_session_signedin]&.starts_with?("SWITCHED")
      GitHub.dogstats.increment("account_switcher.not_found_after_switch")
    end

    elligible
  end

  sig { void }
  def disable_account_switcher_popover
    @disable_account_switcher_popover = true
  end

