  sig { params(uid: String).returns(T::Boolean) }
  def user_disabled_global_banner?(uid)
    return false unless T.unsafe(self).cookies && T.unsafe(self).cookies[:disabled_global_site_banners]
    T.unsafe(self).cookies[:disabled_global_site_banners].split(",").include?(uid)
  end

  sig { params(allowed_paths: T.any(T::Array[String], NilClass), excluded_paths: T.any(T::Array[String], NilClass)).returns(T::Boolean) }
  def allowed_on_pages?(allowed_paths: nil, excluded_paths: nil)
    request = T.let(T.unsafe(self).request, ActionDispatch::Request) # Global request object, passed from the controller
    current_path = request.path

    is_allowed = allowed_paths.nil? || allowed_paths.include?(current_path)
    is_not_excluded = excluded_paths.nil? || !excluded_paths.include?(current_path)

    is_allowed && is_not_excluded
  end

  sig { params(prefix: T.nilable(String), suffix: T.nilable(String)).returns(String) }
  def request_path_parametrize(prefix: "", suffix: "")
    request = T.let(T.unsafe(self).request, ActionDispatch::Request) # Global request object, passed from the controller

    return "" if request.path == "/" || request.path == "/home"
    "#{prefix}#{request.path.force_encoding('UTF-8').parameterize}#{suffix}"
  end

  sig { returns(T::Boolean) }
  def marketing_page?
    controller = T.let(T.unsafe(self).controller, T.any(ActionController::Base, ApplicationController)) # Global controller object
    request = T.let(T.unsafe(self).request, ActionDispatch::Request) # Global request object, passed from the controller
    return true if controller.class == DashboardController && request.path == "/" && !T.unsafe(self).logged_in?
    return true if controller.class.ancestors.include?(Site::BaseController)
    false
  end

  sig { void }
  def marketing_turbo_enable
    @marketing_turbo_disabled = false
  end

  sig { returns(T::Boolean) }
  def marketing_turbo_disabled?
    return @marketing_turbo_disabled if defined? @marketing_turbo_disabled
    return true if marketing_page?
    false
  end

  # ActiveStorage::Filename#sanitize - Characters considered unsafe for storage (e.g. \, $, and the RTL override character) are replaced with a dash.
  # based on https://github.com/github/github/blob/master/packages/apps/app/models/integration_single_file.rb#L25-L30
  sig { params(filename: String).returns(String) }
  def sanitize_filename(filename)
    sanitized = filename.encode(Encoding::UTF_8, invalid: :replace, undef: :replace, replace: "�").strip.tr("\u{202E}\u{202B}\u{200F}%$|:;/\t\r\n\\", "-")
    sanitized.gsub!("..", "") # Remove directory traversal sequences
    sanitized.gsub!(/\A-+|-+\z/, "") # Ensure filename does not start or end with a dash
    sanitized
  end

  # Returns true when the current_user is an EMU
  sig { returns(T::Boolean) }
  def emu?
    T.unsafe(self).current_user&.enterprise_managed_business.present?
  end
